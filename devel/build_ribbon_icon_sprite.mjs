// build_ribbon_icon_sprite.mjs - create the exact Font Awesome SVG subset used by the Ribbon.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  faArrowLeft,
  faBookOpen,
  faCircleUser,
  faClipboardList,
  faEye,
  faFilePen,
  faGear,
  faGraduationCap,
  faListCheck,
  faPalette,
  faPenToSquare,
  faRightFromBracket,
  faStar,
  faTableList,
  faUserGraduate,
  faUsers,
} from "@fortawesome/free-solid-svg-icons";

import {
  RIBBON_CONTEXT_GLYPHS,
  RIBBON_DESTINATION_GLYPHS,
  RIBBON_GLYPH_IDS,
} from "../src/ribbon/ribbon_icons.ts";
import { getRepoRoot } from "./repo_root.mjs";

const SAFE_GLYPH_ID = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u;
const PATH_COMMAND_ARITY = new Map([
  ["M", 2],
  ["L", 2],
  ["H", 1],
  ["V", 1],
  ["C", 6],
  ["S", 4],
  ["Q", 4],
  ["T", 2],
  ["A", 7],
  ["Z", 0],
]);
const PATH_TOKEN = /[a-zA-Z]|[-+]?(?:(?:\d+\.?\d*)|(?:\.\d+))(?:[eE][-+]?\d+)?/uy;
const GENERATED_SPRITE_PREFIX =
  "<!-- Generated by devel/build_ribbon_icon_sprite.mjs. Do not edit by hand. -->\n" +
  '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">\n' +
  "  <defs>\n";
const GENERATED_SPRITE_SUFFIX = "  </defs>\n</svg>\n";
const GENERATED_SYMBOL = new RegExp(
  [
    '^ {4}<symbol id="([a-z][a-z0-9]*(?:-[a-z0-9]+)*)" ',
    'viewBox="0 0 ([1-9]\\d*) ([1-9]\\d*)">\\n',
    '((?: {6}<path d="(?:[^"<&]|&(amp|lt|gt|quot|apos);)+" \\/>\\n)+)',
    " {4}<\\/symbol>$",
  ].join(""),
  "u",
);
const GENERATED_PATH = /^ {6}<path d="((?:[^"<&]|&(amp|lt|gt|quot|apos);)+)" \/>$/u;
const XML_ATTRIBUTE_ENTITIES = new Map([
  ["amp", "&"],
  ["lt", "<"],
  ["gt", ">"],
  ["quot", '"'],
  ["apos", "'"],
]);
/**
 * The generator admits only the glyphs declared by the Ribbon's semantic
 * vocabulary. Keeping this explicit makes an accidental package-wide Font
 * Awesome import impossible and leaves unknown contract glyphs as hard errors.
 */
const FONT_AWESOME_DEFINITIONS = Object.freeze({
  "arrow-left": faArrowLeft,
  "book-open": faBookOpen,
  "circle-user": faCircleUser,
  "clipboard-list": faClipboardList,
  eye: faEye,
  "file-pen": faFilePen,
  gear: faGear,
  "graduation-cap": faGraduationCap,
  "list-check": faListCheck,
  palette: faPalette,
  "pen-to-square": faPenToSquare,
  "right-from-bracket": faRightFromBracket,
  star: faStar,
  "table-list": faTableList,
  "user-graduate": faUserGraduate,
  users: faUsers,
});

function spritePathFor(repoRoot) {
  return path.join(repoRoot, "src/ribbon/assets/ribbon-icons.svg");
}

//============================================

function glyphIdsFromContract() {
  const glyphIds = new Set([
    ...Object.values(RIBBON_DESTINATION_GLYPHS),
    ...Object.values(RIBBON_CONTEXT_GLYPHS),
  ]);
  const glyphIdsSorted = [...glyphIds].sort();
  assertSameGlyphSet([...RIBBON_GLYPH_IDS].sort(), glyphIdsSorted);
  return glyphIdsSorted;
}

//============================================

function iconDefinitionFor(glyphId) {
  const definition = FONT_AWESOME_DEFINITIONS[glyphId];
  if (definition === undefined || typeof definition !== "object" || definition === null) {
    throw new Error(`Font Awesome Free has no solid SVG definition for Ribbon glyph ${glyphId}.`);
  }
  if (!("icon" in definition) || !Array.isArray(definition.icon)) {
    throw new Error(`Font Awesome Free definition for Ribbon glyph ${glyphId} has no icon tuple.`);
  }
  return definition;
}

//============================================

export function validateGlyphId(glyphId) {
  if (typeof glyphId !== "string" || !SAFE_GLYPH_ID.test(glyphId)) {
    throw new Error(`Ribbon glyph ID must be a safe XML identifier: ${String(glyphId)}.`);
  }
  return glyphId;
}

//============================================

export function validateViewBoxDimension(glyphId, dimension, name) {
  if (!Number.isInteger(dimension) || dimension < 1 || dimension > 100_000) {
    throw new Error(`Font Awesome Free glyph ${glyphId} has an invalid ${name}.`);
  }
  return dimension;
}

//============================================

function containsForbiddenControl(value) {
  for (const character of value) {
    const codePoint = character.codePointAt(0);
    if (codePoint <= 0x1f || codePoint === 0x7f) return true;
  }
  return false;
}

//============================================

/**
 * Admit the compact absolute/relative SVG path subset emitted by Font Awesome.
 * This deliberately excludes XML syntax, control characters, and every non-path
 * command before package data reaches the generated SVG document.
 */
export function validatePathData(glyphId, pathData) {
  if (typeof pathData !== "string" || pathData.length === 0 || containsForbiddenControl(pathData)) {
    throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
  }

  const tokens = [];
  let position = 0;
  while (position < pathData.length) {
    if (pathData[position] === " ") {
      position += 1;
      continue;
    }
    if (pathData[position] === ",") {
      const priorToken = tokens.at(-1);
      let nextPosition = position + 1;
      while (pathData[nextPosition] === " ") nextPosition += 1;
      PATH_TOKEN.lastIndex = nextPosition;
      const nextToken = PATH_TOKEN.exec(pathData)?.[0];
      if (
        priorToken === undefined ||
        /^[a-zA-Z]$/u.test(priorToken) ||
        nextToken === undefined ||
        /^[a-zA-Z]$/u.test(nextToken)
      ) {
        throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
      }
      position = nextPosition;
      continue;
    }
    PATH_TOKEN.lastIndex = position;
    const match = PATH_TOKEN.exec(pathData);
    if (match === null) {
      throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
    }
    tokens.push(match[0]);
    position = PATH_TOKEN.lastIndex;
  }

  let command = undefined;
  let parameterCount = 0;
  let sawCommand = false;
  const commandIsComplete = () => {
    const arity = PATH_COMMAND_ARITY.get(command);
    return arity === 0
      ? parameterCount === 0
      : parameterCount >= arity && parameterCount % arity === 0;
  };
  for (const token of tokens) {
    if (/^[a-zA-Z]$/u.test(token)) {
      const upper = token.toUpperCase();
      if (!PATH_COMMAND_ARITY.has(upper)) {
        throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
      }
      if (command !== undefined && !commandIsComplete()) {
        throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
      }
      command = upper;
      parameterCount = 0;
      sawCommand = true;
      continue;
    }
    const numericValue = Number(token);
    if (command === undefined || !Number.isFinite(numericValue)) {
      throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
    }
    const arity = PATH_COMMAND_ARITY.get(command);
    if (arity === 0)
      throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
    if (command === "A") {
      const parameterPosition = parameterCount % arity;
      if (
        ((parameterPosition === 0 || parameterPosition === 1) && numericValue < 0) ||
        ((parameterPosition === 3 || parameterPosition === 4) && !/^[01]$/u.test(token))
      ) {
        throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
      }
    }
    parameterCount += 1;
  }
  if (
    command === undefined ||
    tokens[0]?.toUpperCase() !== "M" ||
    !sawCommand ||
    !commandIsComplete()
  ) {
    throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
  }
  return pathData;
}

//============================================

export function xmlEscapeAttribute(value) {
  return String(value).replace(
    /[&<>"']/gu,
    (character) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&apos;",
      })[character],
  );
}

//============================================

function xmlUnescapeAttribute(value) {
  return value.replace(
    /&(amp|lt|gt|quot|apos);/gu,
    (_entity, name) => XML_ATTRIBUTE_ENTITIES.get(name) ?? "",
  );
}

