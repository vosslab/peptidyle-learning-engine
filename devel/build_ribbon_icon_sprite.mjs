/**
 * Validate the intentionally tiny, exact SVG grammar emitted by renderSprite.
 * Keeping this check in-process makes sprite validation portable while refusing
 * every tag, attribute, order, or entity outside the generator's fixed subset.
 */
export function validateGeneratedSprite(sprite, expectedGlyphIds) {
  if (typeof sprite !== "string" || !Array.isArray(expectedGlyphIds)) {
    throw new Error("Ribbon sprite does not use the generated SVG subset.");
  }
  if (!sprite.startsWith(GENERATED_SPRITE_PREFIX) || !sprite.endsWith(GENERATED_SPRITE_SUFFIX)) {
    throw new Error("Ribbon sprite does not use the generated SVG subset.");
  }

  const symbolText = sprite.slice(GENERATED_SPRITE_PREFIX.length, -GENERATED_SPRITE_SUFFIX.length);
  if (!symbolText.endsWith("\n")) {
    throw new Error("Ribbon sprite does not use the generated SVG subset.");
  }
  const symbols = symbolText.slice(0, -1).split("\n");
  const actualGlyphIds = [];
  let symbolLines = [];
  const validateSymbol = () => {
    const symbol = symbolLines.join("\n");
    const match = GENERATED_SYMBOL.exec(symbol);
    if (match === null) throw new Error("Ribbon sprite does not use the generated SVG subset.");
    validateGlyphId(match[1]);
    validateViewBoxDimension(match[1], Number(match[2]), "viewBox width");
    validateViewBoxDimension(match[1], Number(match[3]), "viewBox height");
    for (const pathLine of match[4].trimEnd().split("\n")) {
      const pathMatch = GENERATED_PATH.exec(pathLine);
      if (pathMatch === null)
        throw new Error("Ribbon sprite does not use the generated SVG subset.");
      validatePathData(match[1], xmlUnescapeAttribute(pathMatch[1]));
    }
    actualGlyphIds.push(match[1]);
    symbolLines = [];
  };
  for (const line of symbols) {
    if (line.startsWith("    <symbol ")) {
      if (symbolLines.length !== 0)
        throw new Error("Ribbon sprite does not use the generated SVG subset.");
      symbolLines.push(line);
    } else if (symbolLines.length !== 0) {
      symbolLines.push(line);
      if (line === "    </symbol>") validateSymbol();
    } else {
      throw new Error("Ribbon sprite does not use the generated SVG subset.");
    }
  }
  if (symbolLines.length !== 0)
    throw new Error("Ribbon sprite does not use the generated SVG subset.");
  assertSameGlyphSet([...expectedGlyphIds].sort(), actualGlyphIds.sort());
  return sprite;
}

//============================================

export function pathsFromDefinition(glyphId, definition) {
  validateGlyphId(glyphId);
  const icon = definition.icon;
  const width = icon[0];
  const height = icon[1];
  const pathData = icon[4];
  validateViewBoxDimension(glyphId, width, "viewBox width");
  validateViewBoxDimension(glyphId, height, "viewBox height");
  const paths = typeof pathData === "string" ? [pathData] : pathData;
  if (
    !Array.isArray(paths) ||
    paths.length === 0 ||
    paths.some((entry) => typeof entry !== "string")
  ) {
    throw new Error(`Font Awesome Free glyph ${glyphId} has invalid SVG path data.`);
  }
  return { width, height, paths: paths.map((entry) => validatePathData(glyphId, entry)) };
}

//============================================

function renderSymbol(glyphId) {
  validateGlyphId(glyphId);
  const definition = iconDefinitionFor(glyphId);
  const { width, height, paths } = pathsFromDefinition(glyphId, definition);
  const renderedPaths = paths
    .map((pathData) => `      <path d="${xmlEscapeAttribute(pathData)}" />`)
    .join("\n");
  const escapedGlyphId = xmlEscapeAttribute(glyphId);
  const escapedWidth = xmlEscapeAttribute(width);
  const escapedHeight = xmlEscapeAttribute(height);
  const symbolOpen =
    `    <symbol id="${escapedGlyphId}" ` + `viewBox="0 0 ${escapedWidth} ${escapedHeight}">`;
  return [symbolOpen, renderedPaths, "    </symbol>"].join("\n");
}

//============================================

export function renderSprite(glyphIds) {
  if (!Array.isArray(glyphIds)) {
    throw new Error("Ribbon sprite glyph IDs must be an array.");
  }
  glyphIds.forEach(validateGlyphId);
  const symbols = glyphIds.map(renderSymbol).join("\n");
  return [
    "<!-- Generated by devel/build_ribbon_icon_sprite.mjs. Do not edit by hand. -->",
    '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">',
    "  <defs>",
    symbols,
    "  </defs>",
    "</svg>",
    "",
  ].join("\n");
}

//============================================

function assertSameGlyphSet(expectedGlyphIds, actualGlyphIds) {
  const expected = expectedGlyphIds.join(", ");
  const actual = actualGlyphIds.join(", ");
  if (expected !== actual) {
    throw new Error(
      "Ribbon sprite glyph IDs differ from the glyph contract. " +
        `Expected: ${expected}. Actual: ${actual}.`,
    );
  }
}

//============================================

function parseCheckMode() {
  const args = process.argv.slice(2);
  if (args.length === 0) return false;
  if (args.length === 1 && args[0] === "--check") return true;
  throw new Error("Usage: node --import tsx devel/build_ribbon_icon_sprite.mjs [--check]");
}

//============================================

export function main() {
  const checkMode = parseCheckMode();
  const repoRoot = getRepoRoot();
  const spritePath = spritePathFor(repoRoot);
  const glyphIds = glyphIdsFromContract();
  const expectedSprite = renderSprite(glyphIds);
  if (checkMode) {
    if (!fs.existsSync(spritePath)) {
      throw new Error("Ribbon icon sprite is missing. Run devel/build_ribbon_icon_sprite.mjs.");
    }
    const committedSprite = fs.readFileSync(spritePath, "utf8");
    validateGeneratedSprite(committedSprite, glyphIds);
    if (committedSprite !== expectedSprite) {
      throw new Error("Ribbon icon sprite is stale. Run devel/build_ribbon_icon_sprite.mjs.");
    }
    console.log("Ribbon icon sprite is current.");
    return;
  }

  fs.mkdirSync(path.dirname(spritePath), { recursive: true });
  fs.writeFileSync(spritePath, expectedSprite);
  console.log(`Wrote ${path.relative(repoRoot, spritePath)}.`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
