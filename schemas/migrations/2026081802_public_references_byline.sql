CREATE OR REPLACE FUNCTION public.ple_project_catalog_search_document() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE stable_question_id character(7);
DECLARE rendered_byline text;
BEGIN
    SELECT question_id INTO stable_question_id FROM public.problem WHERE problem_id = NEW.problem_id;
    SELECT string_agg(value, ', ' ORDER BY ordinality) INTO rendered_byline
      FROM unnest(NEW.public_byline) WITH ORDINALITY AS name(value, ordinality);
    INSERT INTO public.catalog_search_document (
        problem_id, version_id, question_id, title, backend, metadata, publication_scope,
        lifecycle, lifecycle_reason, public_byline, derived_from_problem_id,
        derived_from_version_id, published_at, byline_text, question_type, language, license,
        taxonomy, keywords, capabilities, search_text
    ) VALUES (
        NEW.problem_id, NEW.version_id, stable_question_id, NEW.title, NEW.backend, NEW.metadata,
        NEW.publication_scope, NEW.lifecycle, NEW.lifecycle_reason, NEW.public_byline,
        NEW.derived_from_problem_id, NEW.derived_from_version_id, NEW.created_at, rendered_byline,
        NEW.backend, COALESCE(NEW.metadata->>'language', 'und'),
        COALESCE(NEW.metadata #>> '{license,kind}', 'unknown'),
        COALESCE(NEW.metadata->'taxonomy', '[]'::jsonb), COALESCE(NEW.metadata->'tags', '[]'::jsonb),
        NEW.capabilities, to_tsvector('simple', concat_ws(' ', NEW.title, rendered_byline, NEW.metadata::text))
    ) ON CONFLICT (problem_id, version_id) DO UPDATE SET lifecycle = EXCLUDED.lifecycle,
        lifecycle_reason = EXCLUDED.lifecycle_reason, updated_at = transaction_timestamp();
    RETURN NEW;
END $$;

CREATE VIEW public.catalog_search_view WITH (security_invoker = true) AS
SELECT document.problem_id, document.version_id, document.question_id, document.title, document.backend,
       document.metadata, document.publication_scope, document.lifecycle, document.lifecycle_reason,
       document.public_byline, document.derived_from_problem_id, document.derived_from_version_id,
       document.published_at, document.byline_text, document.question_type, document.language,
       document.license, document.taxonomy, document.keywords, document.capabilities,
       document.search_text, document.quality_signal, document.updated_at, statistics.cohort_size,
       statistics.difficulty_index, statistics.attempts_mean, statistics.time_median_seconds_estimate,
       statistics.discrimination_index, (statistics.cohort_size IS NOT NULL) AS statistics_available,
       document.catalog_sequence, disclosure.disclosed_sequence AS statistics_disclosed_sequence,
       document.normalized_search_text
  FROM public.catalog_search_document AS document
  LEFT JOIN LATERAL public.ple_question_statistics_view(document.problem_id, document.version_id) AS statistics ON true
  LEFT JOIN public.catalog_statistics_disclosure AS disclosure
    ON disclosure.problem_id = document.problem_id AND disclosure.version_id = document.version_id;
GRANT SELECT ON TABLE public.catalog_search_view TO ple_app, ple_student;
