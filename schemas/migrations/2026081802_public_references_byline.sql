CREATE FUNCTION public.ple_valid_public_byline(p_names text[]) RETURNS boolean
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN cardinality(p_names) BETWEEN 1 AND 16
       AND NOT EXISTS (
           SELECT 1 FROM unnest(p_names) AS name
           WHERE name <> btrim(name) OR name = '' OR char_length(name) > 120 OR name ~ '[[:cntrl:]]'
       )
       AND cardinality(p_names) = (SELECT count(DISTINCT name) FROM unnest(p_names) AS name);
ALTER TABLE public.problem_version
    ADD COLUMN public_byline text[] NOT NULL,
    ADD CONSTRAINT problem_version_public_byline_check
        CHECK (public.ple_valid_public_byline(public_byline));

