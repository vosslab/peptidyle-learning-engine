CREATE FUNCTION public.ple_validate_assignment_group_reference_purpose() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE group_purpose text;
BEGIN
    SELECT purpose INTO group_purpose FROM public.course_group
     WHERE tenant_id = NEW.tenant_id AND course_id = NEW.course_id
       AND course_group_id = NEW.course_group_id;
    IF TG_TABLE_NAME = 'assignment_group_accommodation' THEN
        IF group_purpose <> 'accommodation' THEN
            RAISE EXCEPTION 'accommodation modifier requires an accommodation group'
                USING ERRCODE = '23514';
        END IF;
    ELSIF group_purpose NOT IN ('section', 'lab', 'cohort') THEN
        RAISE EXCEPTION 'audience and schedule modifiers require section, lab, or cohort groups'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END
$$;

