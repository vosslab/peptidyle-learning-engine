-- Direct mutations cannot revoke the final current Instructor membership.
CREATE FUNCTION public.ple_guard_final_active_course_instructor() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public'
AS $$
BEGIN
    IF OLD.role = 'instructor' AND OLD.status = 'active'
       AND NEW.status = 'revoked' THEN
        -- Every final-Instructor transition takes this exact parent row before
        -- it counts peers.  The row lock is shared by all membership changes
        -- for this tenant/course, so a second revocation waits, then sees the
        -- first committed revocation and refuses.  No cross-course lock is
        -- acquired, and course deletion cascades DELETE rows rather than this
        -- status UPDATE trigger.
        PERFORM 1 FROM public.course
         WHERE tenant_id = OLD.tenant_id AND course_id = OLD.course_id
         FOR UPDATE;
        IF NOT EXISTS (
            SELECT 1 FROM public.course_member AS other
             WHERE other.tenant_id = OLD.tenant_id AND other.course_id = OLD.course_id
               AND other.role = 'instructor' AND other.status = 'active'
               AND other.course_membership_id <> OLD.course_membership_id
        ) THEN
            RAISE EXCEPTION 'cannot revoke the final active course instructor' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER course_member_final_active_instructor_guard
    BEFORE UPDATE OF status ON public.course_member
    FOR EACH ROW EXECUTE FUNCTION public.ple_guard_final_active_course_instructor();

