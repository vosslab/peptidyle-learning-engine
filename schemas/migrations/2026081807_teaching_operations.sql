CREATE TABLE public.course_instructor_invitation (
    tenant_id uuid NOT NULL,
    course_id uuid NOT NULL,
    invitation_id uuid NOT NULL DEFAULT gen_random_uuid(),
    public_id integer GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME public.course_instructor_invitation_public_id_seq),
    target_user_id uuid NOT NULL REFERENCES public.ple_account(user_id),
    invited_by_membership_id uuid NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT transaction_timestamp(),
    expires_at timestamp with time zone NOT NULL DEFAULT (transaction_timestamp() + interval '30 days'),
    status text NOT NULL DEFAULT 'pending',
    accepted_at timestamp with time zone,
    declined_at timestamp with time zone,
    revoked_at timestamp with time zone,
    accepted_membership_id uuid,
    revision bigint NOT NULL DEFAULT 1,
    CONSTRAINT course_instructor_invitation_pkey PRIMARY KEY (tenant_id, invitation_id),
    CONSTRAINT course_instructor_invitation_public_id_positive CHECK (public_id > 0),
    CONSTRAINT course_instructor_invitation_public_id_key UNIQUE (public_id),
    CONSTRAINT course_instructor_invitation_course_fk
        FOREIGN KEY (tenant_id, course_id)
        REFERENCES public.course(tenant_id, course_id) ON DELETE CASCADE,
    CONSTRAINT course_instructor_invitation_inviter_fk
        FOREIGN KEY (tenant_id, course_id, invited_by_membership_id)
        REFERENCES public.course_member(tenant_id, course_id, course_membership_id) ON DELETE RESTRICT,
    CONSTRAINT course_instructor_invitation_accepted_membership_fk
        FOREIGN KEY (tenant_id, course_id, accepted_membership_id)
        REFERENCES public.course_member(tenant_id, course_id, course_membership_id) ON DELETE RESTRICT,
    CONSTRAINT course_instructor_invitation_status_check
        CHECK (status IN ('pending', 'accepted', 'declined', 'revoked', 'expired')),
    CONSTRAINT course_instructor_invitation_expiry_check
        CHECK (expires_at = created_at + interval '30 days'),
    CONSTRAINT course_instructor_invitation_revision_check CHECK (revision > 0),
    CONSTRAINT course_instructor_invitation_lifecycle_check CHECK (
        (status = 'pending' AND accepted_at IS NULL AND declined_at IS NULL
         AND revoked_at IS NULL AND accepted_membership_id IS NULL)
        OR (status = 'accepted' AND accepted_at IS NOT NULL AND declined_at IS NULL
            AND revoked_at IS NULL AND accepted_membership_id IS NOT NULL)
        OR (status = 'declined' AND accepted_at IS NULL AND declined_at IS NOT NULL
            AND revoked_at IS NULL AND accepted_membership_id IS NULL)
        OR (status = 'revoked' AND accepted_at IS NULL AND declined_at IS NULL
            AND revoked_at IS NOT NULL AND accepted_membership_id IS NULL)
        OR (status = 'expired' AND accepted_at IS NULL AND declined_at IS NULL
            AND revoked_at IS NULL AND accepted_membership_id IS NULL)
    )
);
GRANT USAGE, SELECT ON SEQUENCE public.course_instructor_invitation_public_id_seq TO ple_app;

-- A new invite first expires a prior pending row for the same target/course.
-- The partial unique index then makes concurrent reinvites serialize without
-- permanently blocking a re-invite after the 30 day term.
CREATE UNIQUE INDEX course_instructor_invitation_one_pending_target_key
    ON public.course_instructor_invitation (tenant_id, course_id, target_user_id)
    WHERE status = 'pending';
CREATE INDEX course_instructor_invitation_target_pending_idx
    ON public.course_instructor_invitation (target_user_id, status, expires_at, invitation_id);

CREATE FUNCTION public.ple_expire_pending_course_instructor_invitation() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public'
AS $$
BEGIN
    UPDATE public.course_instructor_invitation
       SET status = 'expired', revision = revision + 1
     WHERE tenant_id = NEW.tenant_id AND course_id = NEW.course_id
       AND target_user_id = NEW.target_user_id AND status = 'pending'
       AND expires_at <= transaction_timestamp();
    RETURN NEW;
END
$$;

CREATE FUNCTION public.ple_guard_course_instructor_invitation() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public'
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'pending' OR NEW.revision <> 1
           OR NEW.created_at <> transaction_timestamp()
           OR NEW.expires_at <> NEW.created_at + interval '30 days'
           OR NOT public.ple_instructor_approval_eligible(NEW.target_user_id)
           OR NOT EXISTS (
                SELECT 1 FROM public.course_member
                 WHERE tenant_id = NEW.tenant_id AND course_id = NEW.course_id
                   AND course_membership_id = NEW.invited_by_membership_id
                   AND role = 'instructor' AND status = 'active'
           ) THEN
            RAISE EXCEPTION 'invalid co-instructor invitation' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF (NEW.tenant_id, NEW.course_id, NEW.invitation_id, NEW.target_user_id,
        NEW.invited_by_membership_id, NEW.created_at, NEW.expires_at)
       IS DISTINCT FROM
       (OLD.tenant_id, OLD.course_id, OLD.invitation_id, OLD.target_user_id,
        OLD.invited_by_membership_id, OLD.created_at, OLD.expires_at)
       OR NEW.revision <> OLD.revision + 1 THEN
        RAISE EXCEPTION 'co-instructor invitation identity is immutable' USING ERRCODE = '55000';
    END IF;
    IF OLD.status <> 'pending' THEN
        RAISE EXCEPTION 'terminal co-instructor invitation is immutable' USING ERRCODE = '55000';
    END IF;
    IF NEW.status = 'accepted' THEN
        IF transaction_timestamp() >= OLD.expires_at
           OR NOT public.ple_instructor_approval_eligible(OLD.target_user_id)
           OR NEW.accepted_at <> transaction_timestamp()
           OR NOT EXISTS (
                SELECT 1 FROM public.course_member
                 WHERE tenant_id = OLD.tenant_id AND course_id = OLD.course_id
                   AND course_membership_id = NEW.accepted_membership_id
                   AND user_id = OLD.target_user_id AND role = 'instructor' AND status = 'active'
           ) THEN
            RAISE EXCEPTION 'invalid co-instructor invitation acceptance' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status = 'declined' THEN
        IF NEW.revoked_at IS NOT NULL OR NEW.declined_at <> transaction_timestamp() THEN
            RAISE EXCEPTION 'invalid co-instructor invitation terminal state' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status = 'revoked' THEN
        IF NEW.declined_at IS NOT NULL OR NEW.revoked_at <> transaction_timestamp() THEN
            RAISE EXCEPTION 'invalid co-instructor invitation terminal state' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status = 'expired' THEN
        IF transaction_timestamp() < OLD.expires_at
           OR NEW.accepted_at IS NOT NULL OR NEW.declined_at IS NOT NULL
           OR NEW.revoked_at IS NOT NULL THEN
            RAISE EXCEPTION 'co-instructor invitation is not expired' USING ERRCODE = '23514';
        END IF;
    ELSE
        RAISE EXCEPTION 'co-instructor invitation may only leave pending once' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END
$$;

