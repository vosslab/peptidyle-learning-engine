-- Approval is global operator eligibility.  It intentionally has neither a
-- tenant key nor RLS policy, and it does not confer a platform or course role.
CREATE TABLE public.instructor_approval (
    user_id uuid PRIMARY KEY REFERENCES public.ple_account(user_id),
    approved_by uuid NOT NULL REFERENCES public.ple_account(user_id),
    approved_at timestamp with time zone NOT NULL,
    revoked_at timestamp with time zone,
    revision bigint NOT NULL,
    CONSTRAINT instructor_approval_revision_check CHECK (revision > 0),
    CONSTRAINT instructor_approval_chronology_check
        CHECK (revoked_at IS NULL OR revoked_at >= approved_at)
);

CREATE FUNCTION public.ple_instructor_approval_eligible(p_target uuid) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
    SELECT p_target IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.instructor_approval
         WHERE user_id = p_target AND revoked_at IS NULL
    )
$$;

-- Pending invitations are target-bound, so the application may resolve only
-- the subject of the presented active session.  Direct `auth_session` access
-- remains unavailable to `ple_app`; this broker returns no session metadata.
CREATE FUNCTION public.ple_target_session_subject(
    p_session character(64), p_tenant uuid
) RETURNS TABLE (user_id uuid)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
    SELECT session.user_id
      FROM public.auth_session AS session
     WHERE session.session_hash = p_session
       AND session.tenant_id = p_tenant
       AND session.tenant_id = public.ple_current_tenant()
       AND session.revoked_at IS NULL
       AND session.expires_at > transaction_timestamp()
$$;

-- The application has no direct access to global account rows.  Invitation
-- creation still distinguishes a nonexistent target from an existing but
-- unapproved target through this account-ID-only broker predicate.
CREATE FUNCTION public.ple_instructor_approval_target_exists(p_target uuid) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
    SELECT p_target IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.ple_account WHERE user_id = p_target
    )
$$;

-- These are the only account-reference projections available to `ple_app`.
-- They intentionally return neither normalized nor delivery email.  The
-- session-bound variants check the persisted, active same-tenant session in
-- the broker, rather than trusting caller-supplied identity or role inputs.
CREATE FUNCTION public.ple_own_account_reference(
    p_session character(64), p_tenant uuid
) RETURNS TABLE (public_id integer, display_name text)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
    SELECT account.public_id, account.display_name
      FROM public.auth_session AS session
      JOIN public.ple_account AS account ON account.user_id = session.user_id
     WHERE session.session_hash = p_session
       AND session.tenant_id = p_tenant
       AND session.tenant_id = public.ple_current_tenant()
       AND session.revoked_at IS NULL
       AND session.expires_at > transaction_timestamp()
$$;

CREATE FUNCTION public.ple_sysadmin_account_reference(
    p_session character(64), p_public_id integer
) RETURNS TABLE (user_id uuid)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE actor uuid;
DECLARE roles jsonb;
BEGIN
    SELECT session.user_id, session.roles INTO actor, roles
      FROM public.auth_session AS session
     WHERE session.session_hash = p_session
       AND session.tenant_id = public.ple_current_tenant()
       AND session.revoked_at IS NULL
       AND session.expires_at > transaction_timestamp();
    IF actor IS NULL THEN
        RETURN;
    END IF;
    IF NOT roles @> '["sysadmin"]'::jsonb THEN
        RAISE EXCEPTION 'sysadmin account reference is not authorized' USING ERRCODE = '42501';
    END IF;
    RETURN QUERY SELECT account.user_id
      FROM public.ple_account AS account WHERE account.public_id = p_public_id;
END
$$;

CREATE FUNCTION public.ple_approved_account_reference(
    p_public_id integer
) RETURNS TABLE (user_id uuid)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
    SELECT account.user_id
      FROM public.ple_account AS account
      JOIN public.instructor_approval AS approval ON approval.user_id = account.user_id
     WHERE account.public_id = p_public_id AND approval.revoked_at IS NULL
$$;

-- Acceptance must hold this exact approval row through its membership and
-- invitation writes.  Sysadmin approval and revocation use the same row lock,
-- so either transition serializes before acceptance can commit.
CREATE FUNCTION public.ple_lock_instructor_approval_eligibility(p_target uuid) RETURNS boolean
    LANGUAGE plpgsql VOLATILE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE stored public.instructor_approval%ROWTYPE;
BEGIN
    IF p_target IS NULL THEN
        RETURN false;
    END IF;
    SELECT * INTO stored FROM public.instructor_approval
     WHERE user_id = p_target FOR UPDATE;
    RETURN FOUND AND stored.revoked_at IS NULL;
END
$$;

CREATE FUNCTION public.ple_sysadmin_instructor_approval(
    p_session character,
    p_target uuid,
    p_expected_revision bigint DEFAULT NULL
) RETURNS TABLE (
    user_id uuid, approved_by uuid, approved_at timestamp with time zone,
    revoked_at timestamp with time zone, revision bigint
)
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE actor uuid;
DECLARE roles jsonb;
DECLARE stored public.instructor_approval%ROWTYPE;
BEGIN
    PERFORM set_config('ple.session_hash', p_session, true);
    SELECT session.user_id, session.roles INTO actor, roles
      FROM public.auth_session AS session
     WHERE session.session_hash = p_session
       AND session.tenant_id = public.ple_current_tenant()
       AND session.revoked_at IS NULL
       AND session.expires_at > transaction_timestamp();
    IF actor IS NULL OR NOT roles @> '["sysadmin"]'::jsonb OR p_target IS NULL THEN
        RAISE EXCEPTION 'sysadmin instructor approval is not authorized' USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.ple_account AS account
         WHERE account.user_id = p_target
    ) THEN
        RETURN;
    END IF;
    SELECT * INTO stored FROM public.instructor_approval AS approval
     WHERE approval.user_id = p_target FOR UPDATE;
    IF FOUND AND p_expected_revision IS DISTINCT FROM stored.revision THEN
        RAISE EXCEPTION 'stale instructor approval revision' USING ERRCODE = '55000';
    END IF;
    IF NOT FOUND AND p_expected_revision IS NOT NULL THEN
        RAISE EXCEPTION 'stale instructor approval revision' USING ERRCODE = '55000';
    END IF;
    IF NOT FOUND THEN
        INSERT INTO public.instructor_approval
            (user_id, approved_by, approved_at, revoked_at, revision)
        VALUES (p_target, actor, transaction_timestamp(), NULL, 1)
        RETURNING * INTO stored;
    ELSE
        UPDATE public.instructor_approval AS approval
           SET approved_by = actor, approved_at = transaction_timestamp(), revoked_at = NULL,
               revision = approval.revision + 1
         WHERE approval.user_id = p_target RETURNING * INTO stored;
    END IF;
    RETURN QUERY SELECT stored.user_id, stored.approved_by, stored.approved_at,
                        stored.revoked_at, stored.revision;
END
$$;

CREATE FUNCTION public.ple_sysadmin_revoke_instructor_approval(
    p_session character, p_target uuid, p_expected_revision bigint
) RETURNS TABLE (
    user_id uuid, approved_by uuid, approved_at timestamp with time zone,
    revoked_at timestamp with time zone, revision bigint
)
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
AS $$
DECLARE actor uuid;
DECLARE roles jsonb;
DECLARE stored public.instructor_approval%ROWTYPE;
BEGIN
    PERFORM set_config('ple.session_hash', p_session, true);
    SELECT session.user_id, session.roles INTO actor, roles
      FROM public.auth_session AS session
     WHERE session.session_hash = p_session
       AND session.tenant_id = public.ple_current_tenant()
       AND session.revoked_at IS NULL
       AND session.expires_at > transaction_timestamp();
    IF actor IS NULL OR NOT roles @> '["sysadmin"]'::jsonb OR p_target IS NULL THEN
        RAISE EXCEPTION 'sysadmin instructor approval is not authorized' USING ERRCODE = '42501';
    END IF;
    SELECT * INTO stored FROM public.instructor_approval AS approval
     WHERE approval.user_id = p_target FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    IF stored.revoked_at IS NOT NULL
       OR p_expected_revision IS DISTINCT FROM stored.revision THEN
        RAISE EXCEPTION 'stale instructor approval revision' USING ERRCODE = '55000';
    END IF;
    UPDATE public.instructor_approval AS approval
       SET revoked_at = transaction_timestamp(), revision = approval.revision + 1
     WHERE approval.user_id = p_target RETURNING * INTO stored;
    RETURN QUERY SELECT stored.user_id, stored.approved_by, stored.approved_at,
                        stored.revoked_at, stored.revision;
END
$$;

