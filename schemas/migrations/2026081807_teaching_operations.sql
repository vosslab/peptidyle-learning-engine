CREATE TABLE public.course_group_membership_policy (
    tenant_id uuid NOT NULL,
    course_id uuid NOT NULL,
    purpose text NOT NULL,
    multiple_membership text NOT NULL,
    revision bigint NOT NULL,
    CONSTRAINT course_group_membership_policy_pkey
        PRIMARY KEY (tenant_id, course_id, purpose),
    CONSTRAINT course_group_membership_policy_course_fk
        FOREIGN KEY (tenant_id, course_id)
        REFERENCES public.course(tenant_id, course_id) ON DELETE CASCADE,
    CONSTRAINT course_group_membership_policy_purpose_check
        CHECK (purpose IN ('section', 'lab', 'cohort', 'accommodation', 'work')),
    CONSTRAINT course_group_membership_policy_multiple_check
        CHECK (multiple_membership IN ('allow', 'warn')),
    CONSTRAINT course_group_membership_policy_revision_check CHECK (revision > 0)
