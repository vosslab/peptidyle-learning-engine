       defaults.multiple_membership, 1
  FROM public.course AS course
 CROSS JOIN (VALUES
    ('section'::text, 'warn'::text),
    ('lab'::text, 'allow'::text),
    ('cohort'::text, 'allow'::text),
    ('accommodation'::text, 'allow'::text),
    ('work'::text, 'allow'::text)
 ) AS defaults(purpose, multiple_membership);

