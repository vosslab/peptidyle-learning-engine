-- Rehearsal evidence is canonical Unix milliseconds, selected by PostgreSQL.
CREATE FUNCTION public.ple_rehearsal_now() RETURNS timestamp with time zone LANGUAGE sql STABLE SET search_path TO 'pg_catalog', 'public', pg_temp AS $$ SELECT date_trunc('milliseconds', transaction_timestamp()) $$;
-- App-facing milliseconds use this broker-owned definer capability; the inner timestamp stays broker-private.
CREATE FUNCTION public.ple_rehearsal_now_millis() RETURNS bigint
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$ SELECT (extract(epoch FROM public.ple_rehearsal_now()) * 1000)::bigint $$;
CREATE FUNCTION public.ple_rehearsal_timestamp_from_millis(p_millis bigint)
    RETURNS timestamp with time zone LANGUAGE sql IMMUTABLE STRICT SET search_path TO 'pg_catalog', 'public', pg_temp AS $$ SELECT timestamptz 'epoch' + p_millis * interval '1 millisecond' $$;
-- v1 JSONB admission uses PostgreSQL's deterministic canonical text representation.
CREATE FUNCTION public.ple_rehearsal_jsonb_bytes(p_value jsonb) RETURNS bigint LANGUAGE sql IMMUTABLE STRICT SET search_path TO 'pg_catalog', 'public', pg_temp AS $$ SELECT octet_length(p_value::text) $$;
