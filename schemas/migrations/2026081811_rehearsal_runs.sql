CREATE FUNCTION public.ple_reject_rehearsal_append_only_mutation() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
BEGIN
    RAISE EXCEPTION 'rehearsal evidence and claim records are append-only' USING ERRCODE = '55000';
END
$$;
CREATE FUNCTION public.ple_guard_rehearsal_run_update() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
BEGIN
    IF (NEW.tenant_id, NEW.rehearsal_run_id, NEW.rehearsal_reference, NEW.course_id,
        NEW.assignment_id, NEW.assignment_reference, NEW.direct_instructor_membership_id,
        NEW.actor_id, NEW.assignment_revision, NEW.subject_payload, NEW.subject_fingerprint,
        NEW.started_at) IS DISTINCT FROM
       (OLD.tenant_id, OLD.rehearsal_run_id, OLD.rehearsal_reference, OLD.course_id,
        OLD.assignment_id, OLD.assignment_reference, OLD.direct_instructor_membership_id,
        OLD.actor_id, OLD.assignment_revision, OLD.subject_payload, OLD.subject_fingerprint,
        OLD.started_at) THEN
        RAISE EXCEPTION 'rehearsal provenance is immutable' USING ERRCODE = '55000';
    END IF;
    IF current_user <> 'ple_rehearsal_broker' THEN
        RAISE EXCEPTION 'rehearsal run mutation requires broker capability' USING ERRCODE = '42501';
    END IF;
    IF NEW.updated_at <> public.ple_rehearsal_now() THEN
        RAISE EXCEPTION 'rehearsal timestamps are database controlled' USING ERRCODE = '22023';
    END IF;
    IF OLD.lifecycle <> 'active' AND NEW.lifecycle IS DISTINCT FROM OLD.lifecycle THEN
        RAISE EXCEPTION 'terminal rehearsal lifecycle is immutable' USING ERRCODE = '55000';
    END IF;
    IF OLD.lifecycle = 'active' AND NEW.lifecycle = 'active'
       AND (NEW.terminal_at IS DISTINCT FROM OLD.terminal_at OR NEW.terminal_at IS NOT NULL) THEN
        RAISE EXCEPTION 'active rehearsal cannot have a terminal timestamp' USING ERRCODE = '22023';
    END IF;
    IF OLD.lifecycle = 'active' AND NEW.lifecycle <> 'active'
       AND NEW.terminal_at <> public.ple_rehearsal_now() THEN
        RAISE EXCEPTION 'terminal rehearsal timestamp is database controlled' USING ERRCODE = '22023';
    END IF;
    IF NEW.evidence_length < OLD.evidence_length THEN
        RAISE EXCEPTION 'rehearsal evidence head cannot regress' USING ERRCODE = '55000';
    END IF;
    IF NEW.evidence_length = OLD.evidence_length
       AND NEW.evidence_head_digest IS DISTINCT FROM OLD.evidence_head_digest THEN
        RAISE EXCEPTION 'rehearsal evidence head cannot change without an append' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END
$$;
