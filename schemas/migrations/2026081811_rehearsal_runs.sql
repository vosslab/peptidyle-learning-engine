-- Exact live instructor and assignment binding.  Callers provide locators, not
-- authority: the relation is locked and proves actor, membership, course, and
-- current revision together.
CREATE FUNCTION public.ple_rehearsal_authorize_current(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_revision bigint
) RETURNS uuid
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE membership uuid;
BEGIN
    IF p_tenant IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant()
       OR p_actor IS NULL OR p_course IS NULL OR p_assignment IS NULL OR p_revision <= 0 THEN
        RETURN NULL;
    END IF;
    PERFORM 1 FROM public.assignment AS assignment_record
     WHERE assignment_record.tenant_id = p_tenant AND assignment_record.course_id = p_course
       AND assignment_record.assignment_id = p_assignment AND assignment_record.revision = p_revision
     FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT member.course_membership_id INTO membership
      FROM public.course_member AS member
     WHERE member.tenant_id = p_tenant AND member.course_id = p_course
       AND member.user_id = p_actor AND member.role = 'instructor' AND member.status = 'active'
     FOR UPDATE;
    IF membership IS NULL THEN RETURN NULL; END IF;
    RETURN membership;
END
$$;
CREATE FUNCTION public.ple_rehearsal_start(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_assignment_reference integer,
    p_revision bigint, p_subject_payload jsonb, p_subject_fingerprint bytea,
    p_genesis_digest bytea, p_run uuid
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE membership uuid; reference bigint; active_run public.rehearsal_run%ROWTYPE;
BEGIN
    membership := public.ple_rehearsal_authorize_current(
        p_tenant, p_actor, p_course, p_assignment, p_revision
    );
    IF membership IS NULL OR p_run IS NULL OR p_assignment_reference <= 0
       OR jsonb_typeof(p_subject_payload) <> 'object'
       OR public.ple_rehearsal_jsonb_bytes(p_subject_payload) > 65536
       OR octet_length(p_subject_fingerprint) <> 32 OR octet_length(p_genesis_digest) <> 32 THEN
        RETURN NULL;
    END IF;
    SELECT * INTO active_run
      FROM public.rehearsal_run
     WHERE tenant_id = p_tenant AND course_id = p_course AND assignment_id = p_assignment
       AND direct_instructor_membership_id = membership AND lifecycle = 'active'
     FOR UPDATE;
    IF FOUND THEN
        IF active_run.assignment_revision <> p_revision THEN
            RETURN NULL;
        END IF;
        IF active_run.subject_fingerprint = p_subject_fingerprint
           AND active_run.actor_id = p_actor THEN
            RETURN active_run.rehearsal_reference;
        END IF;
        INSERT INTO public.rehearsal_submission_claim_event (
            tenant_id, rehearsal_run_id, claim_id, sequence, operation_id, generation, phase
        )
        SELECT root.tenant_id, root.rehearsal_run_id, root.claim_id, latest.sequence + 1,
               latest.operation_id, latest.generation, 'revokedTerminalLifecycle'
          FROM public.rehearsal_submission_claim_root root
          CROSS JOIN LATERAL (
              SELECT event.sequence, event.operation_id, event.generation, event.phase
                FROM public.rehearsal_submission_claim_event event
               WHERE event.tenant_id = root.tenant_id
                 AND event.rehearsal_run_id = root.rehearsal_run_id
                 AND event.claim_id = root.claim_id
               ORDER BY event.sequence DESC LIMIT 1
          ) latest
         WHERE root.tenant_id = p_tenant AND root.rehearsal_run_id = active_run.rehearsal_run_id
           AND latest.phase IN ('prepared', 'gradingDispatched');
        UPDATE public.rehearsal_run
           SET lifecycle = 'discardedByNewSubject', terminal_at = public.ple_rehearsal_now(),
               updated_at = public.ple_rehearsal_now()
         WHERE tenant_id = p_tenant AND rehearsal_run_id = active_run.rehearsal_run_id
           AND lifecycle = 'active';
        IF NOT FOUND THEN
            RAISE EXCEPTION 'active rehearsal changed during replacement' USING ERRCODE = '55000';
        END IF;
    END IF;
    INSERT INTO public.rehearsal_run (
        tenant_id, rehearsal_run_id, course_id, assignment_id, assignment_reference,
        direct_instructor_membership_id, actor_id, assignment_revision, subject_payload,
        subject_fingerprint, evidence_head_digest, evidence_length
    ) VALUES (
        p_tenant, p_run, p_course, p_assignment, p_assignment_reference, membership, p_actor,
        p_revision, p_subject_payload, p_subject_fingerprint, p_genesis_digest, 0
    ) RETURNING rehearsal_reference INTO reference;
    RETURN reference;
END
$$;
-- The caller must already have assembled canonical private evidence. This
-- function deliberately does not reimplement Rust hashing; it serializes the
-- checked payload and only accepts the next Store-owned chain position.
CREATE FUNCTION public.ple_rehearsal_append_evidence(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_revision bigint,
    p_run uuid, p_old_digest bytea, p_old_length bigint, p_kind text, p_entry_digest bytea,
    p_payload jsonb, p_payload_digest bytea, p_recorded_at_millis bigint
) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE membership uuid; locked_run public.rehearsal_run%ROWTYPE; next_sequence bigint;
BEGIN
    membership := public.ple_rehearsal_authorize_current(p_tenant, p_actor, p_course, p_assignment, p_revision);
    IF membership IS NULL OR p_run IS NULL OR p_old_length NOT BETWEEN 0 AND 4294967295
       OR p_kind NOT IN ('frozenItem', 'acceptedSubmission') OR jsonb_typeof(p_payload) <> 'object'
       OR public.ple_rehearsal_jsonb_bytes(p_payload) > (CASE p_kind WHEN 'frozenItem' THEN 263168 WHEN 'acceptedSubmission' THEN 395264 ELSE 0 END)
       OR octet_length(p_old_digest) <> 32 OR octet_length(p_entry_digest) <> 32
       OR octet_length(p_payload_digest) <> 32
       OR p_recorded_at_millis <> public.ple_rehearsal_now_millis() THEN RETURN false; END IF;
    SELECT * INTO locked_run FROM public.rehearsal_run
     WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run
       AND course_id = p_course AND assignment_id = p_assignment AND actor_id = p_actor
       AND direct_instructor_membership_id = membership AND assignment_revision = p_revision
       AND lifecycle = 'active' FOR UPDATE;
    IF NOT FOUND OR locked_run.evidence_head_digest IS DISTINCT FROM p_old_digest
       OR locked_run.evidence_length <> p_old_length THEN RETURN false; END IF;
    next_sequence := p_old_length + 1;
    INSERT INTO public.rehearsal_evidence (
        tenant_id, rehearsal_run_id, sequence, kind, previous_digest, entry_digest,
        payload, payload_digest, recorded_at
    ) VALUES (p_tenant, p_run, next_sequence, p_kind, p_old_digest, p_entry_digest,
              p_payload, p_payload_digest, public.ple_rehearsal_timestamp_from_millis(p_recorded_at_millis));
    UPDATE public.rehearsal_run SET evidence_head_digest = p_entry_digest,
        evidence_length = next_sequence, updated_at = public.ple_rehearsal_now()
     WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run
       AND evidence_head_digest = p_old_digest AND evidence_length = p_old_length;
    IF NOT FOUND THEN RAISE EXCEPTION 'rehearsal evidence head compare-and-swap failed' USING ERRCODE = '55000'; END IF;
    RETURN true;
END
$$;
CREATE FUNCTION public.ple_rehearsal_terminalize(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_revision bigint,
    p_run uuid, p_lifecycle text
) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE membership uuid;
BEGIN
    membership := public.ple_rehearsal_authorize_current(p_tenant, p_actor, p_course, p_assignment, p_revision);
    IF membership IS NULL OR p_lifecycle NOT IN ('completed', 'discardedByInstructor', 'discardedByNewSubject') THEN
        RETURN false;
    END IF;
    PERFORM 1 FROM public.rehearsal_run
     WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run AND course_id = p_course
       AND assignment_id = p_assignment AND actor_id = p_actor
       AND direct_instructor_membership_id = membership AND assignment_revision = p_revision
       AND lifecycle = 'active' FOR UPDATE;
    IF NOT FOUND THEN RETURN false; END IF;
    INSERT INTO public.rehearsal_submission_claim_event (
        tenant_id, rehearsal_run_id, claim_id, sequence, operation_id, generation, phase
    )
    SELECT root.tenant_id, root.rehearsal_run_id, root.claim_id, latest.sequence + 1,
           latest.operation_id, latest.generation, 'revokedTerminalLifecycle'
      FROM public.rehearsal_submission_claim_root root
      CROSS JOIN LATERAL (
          SELECT event.sequence, event.operation_id, event.generation, event.phase
            FROM public.rehearsal_submission_claim_event event
           WHERE event.tenant_id = root.tenant_id AND event.rehearsal_run_id = root.rehearsal_run_id
             AND event.claim_id = root.claim_id ORDER BY event.sequence DESC LIMIT 1
      ) latest
     WHERE root.tenant_id = p_tenant AND root.rehearsal_run_id = p_run
       AND latest.phase IN ('prepared', 'gradingDispatched');
    UPDATE public.rehearsal_run SET lifecycle = p_lifecycle, terminal_at = public.ple_rehearsal_now(),
        updated_at = public.ple_rehearsal_now()
     WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run AND course_id = p_course
       AND assignment_id = p_assignment AND actor_id = p_actor
       AND direct_instructor_membership_id = membership AND assignment_revision = p_revision
       AND lifecycle = 'active';
    RETURN FOUND;
END
$$;
CREATE FUNCTION public.ple_rehearsal_append_frozen_item(
