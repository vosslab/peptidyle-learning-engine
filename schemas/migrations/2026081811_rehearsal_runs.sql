    ) VALUES (
        p_tenant, p_run, p_claim, latest.sequence + 1, p_operation, latest.generation, 'completed',
        p_old_length + 1, p_entry_digest, p_receipt_digest
    );
    RETURN true;
END
$$;
CREATE FUNCTION public.ple_rehearsal_evidence_is_contiguous(
    p_tenant uuid, p_run uuid, p_expected_length bigint
) RETURNS boolean
    LANGUAGE sql STABLE
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
SELECT CASE
    WHEN p_tenant IS NULL OR p_run IS NULL
      OR p_expected_length NOT BETWEEN 0 AND 4294967295 THEN false
    WHEN p_expected_length = 0 THEN NOT EXISTS (
        SELECT 1 FROM public.rehearsal_evidence
         WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run
    )
    ELSE (SELECT COUNT(*) = p_expected_length AND MIN(sequence) = 1
                    AND MAX(sequence) = p_expected_length
            FROM public.rehearsal_evidence
           WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run)
END
$$;
CREATE FUNCTION public.ple_invalidate_rehearsals_for_assignment(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_old_revision bigint, p_new_revision bigint
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE changed bigint;
BEGIN
    IF p_old_revision <= 0 OR p_new_revision <> p_old_revision + 1
       OR public.ple_rehearsal_authorize_current(
        p_tenant, p_actor, p_course, p_assignment, p_new_revision
    ) IS NULL THEN
        RAISE EXCEPTION 'invalid rehearsal revision invalidation' USING ERRCODE = '22023';
    END IF;
    PERFORM 1 FROM public.rehearsal_run
     WHERE tenant_id = p_tenant AND assignment_id = p_assignment
       AND assignment_revision = p_old_revision AND lifecycle = 'active'
     ORDER BY rehearsal_run_id FOR UPDATE;
    -- Rust performs the stronger canonical hash verification after this SQL shape guard.
    IF EXISTS (
        SELECT 1 FROM public.rehearsal_run run
         WHERE run.tenant_id = p_tenant AND run.assignment_id = p_assignment
           AND run.assignment_revision = p_old_revision AND run.lifecycle = 'active'
           AND NOT public.ple_rehearsal_evidence_is_contiguous(
               run.tenant_id, run.rehearsal_run_id, run.evidence_length)
    ) THEN RAISE EXCEPTION 'rehearsal aggregate structural verification failed' USING ERRCODE = '55000'; END IF;
    INSERT INTO public.rehearsal_submission_claim_event (
        tenant_id, rehearsal_run_id, claim_id, sequence, operation_id, generation, phase
    )
    SELECT root.tenant_id, root.rehearsal_run_id, root.claim_id,
           latest.sequence + 1, latest.operation_id, latest.generation, 'revokedStaleRevision'
      FROM public.rehearsal_submission_claim_root root
      JOIN public.rehearsal_run run ON run.tenant_id = root.tenant_id AND run.rehearsal_run_id = root.rehearsal_run_id
      CROSS JOIN LATERAL (
          SELECT event.sequence, event.operation_id, event.generation, event.phase
            FROM public.rehearsal_submission_claim_event event
           WHERE event.tenant_id = root.tenant_id AND event.rehearsal_run_id = root.rehearsal_run_id
             AND event.claim_id = root.claim_id ORDER BY event.sequence DESC LIMIT 1
      ) latest
     WHERE root.tenant_id = p_tenant AND run.assignment_id = p_assignment
       AND run.assignment_revision = p_old_revision AND run.lifecycle = 'active'
       AND latest.phase IN ('prepared', 'gradingDispatched');
    UPDATE public.rehearsal_run SET lifecycle = 'discardedStaleRevision', terminal_at = public.ple_rehearsal_now(),
        updated_at = public.ple_rehearsal_now()
     WHERE tenant_id = p_tenant AND assignment_id = p_assignment
       AND assignment_revision = p_old_revision AND lifecycle = 'active';
    GET DIAGNOSTICS changed = ROW_COUNT;
    RETURN changed;
END
$$;
CREATE FUNCTION public.ple_rehearsal_fence_source_context(
    p_tenant uuid, p_course uuid, p_assignment uuid, p_membership uuid
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE fenced bigint; source_course uuid;
BEGIN
    IF p_tenant IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant()
       OR ((p_course IS NOT NULL)::integer + (p_assignment IS NOT NULL)::integer
           + (p_membership IS NOT NULL)::integer) <> 1 THEN
        RAISE EXCEPTION 'invalid rehearsal source-removal capability' USING ERRCODE = '42501';
    END IF;
    IF p_course IS NOT NULL THEN
        PERFORM 1 FROM public.assignment assignment_record
         WHERE assignment_record.tenant_id = p_tenant AND assignment_record.course_id = p_course
         ORDER BY assignment_record.assignment_id FOR UPDATE;
        PERFORM 1 FROM public.course_member membership
         WHERE membership.tenant_id = p_tenant AND membership.course_id = p_course
           AND membership.role = 'instructor' AND membership.status = 'active'
         ORDER BY membership.course_membership_id FOR UPDATE;
    ELSIF p_assignment IS NOT NULL THEN
        SELECT assignment_record.course_id INTO source_course
          FROM public.assignment assignment_record
         WHERE assignment_record.tenant_id = p_tenant
           AND assignment_record.assignment_id = p_assignment
         ;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'assignment source is already absent' USING ERRCODE = '55000';
        END IF;
        PERFORM 1 FROM public.assignment assignment_record
         WHERE assignment_record.tenant_id = p_tenant AND assignment_record.course_id = source_course
           AND assignment_record.assignment_id = p_assignment FOR UPDATE;
        PERFORM 1 FROM public.course_member membership
         WHERE membership.tenant_id = p_tenant AND membership.course_id = source_course
           AND membership.role = 'instructor' AND membership.status = 'active'
         ORDER BY membership.course_membership_id FOR UPDATE;
    ELSE
        SELECT membership.course_id INTO source_course
          FROM public.course_member membership
         WHERE membership.tenant_id = p_tenant
           AND membership.course_membership_id = p_membership
         FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'membership source is already absent' USING ERRCODE = '55000';
        END IF;
    END IF;
    PERFORM 1 FROM public.rehearsal_run run
     WHERE run.tenant_id = p_tenant AND run.lifecycle = 'active'
       AND ((p_course IS NOT NULL AND run.course_id = p_course)
         OR (p_assignment IS NOT NULL AND run.assignment_id = p_assignment)
         OR (p_membership IS NOT NULL AND run.direct_instructor_membership_id = p_membership))
     ORDER BY run.rehearsal_run_id FOR UPDATE;
    IF EXISTS (
        SELECT 1 FROM public.rehearsal_run run
         WHERE run.tenant_id = p_tenant AND run.lifecycle = 'active'
           AND ((p_course IS NOT NULL AND run.course_id = p_course)
             OR (p_assignment IS NOT NULL AND run.assignment_id = p_assignment)
             OR (p_membership IS NOT NULL AND run.direct_instructor_membership_id = p_membership))
           AND NOT public.ple_rehearsal_evidence_is_contiguous(
               run.tenant_id, run.rehearsal_run_id, run.evidence_length)
    ) THEN RAISE EXCEPTION 'rehearsal aggregate structural verification failed' USING ERRCODE = '55000'; END IF;
    INSERT INTO public.rehearsal_submission_claim_event (
        tenant_id, rehearsal_run_id, claim_id, sequence, operation_id, generation, phase
    )
    SELECT root.tenant_id, root.rehearsal_run_id, root.claim_id, latest.sequence + 1,
           latest.operation_id, latest.generation, 'revokedSourceContextRemoved'
      FROM public.rehearsal_submission_claim_root root
      JOIN public.rehearsal_run run ON run.tenant_id = root.tenant_id AND run.rehearsal_run_id = root.rehearsal_run_id
      CROSS JOIN LATERAL (
          SELECT event.sequence, event.operation_id, event.generation, event.phase
            FROM public.rehearsal_submission_claim_event event
           WHERE event.tenant_id = root.tenant_id AND event.rehearsal_run_id = root.rehearsal_run_id
             AND event.claim_id = root.claim_id ORDER BY event.sequence DESC LIMIT 1
      ) latest
     WHERE root.tenant_id = p_tenant AND run.lifecycle = 'active'
       AND ((p_course IS NOT NULL AND run.course_id = p_course)
         OR (p_assignment IS NOT NULL AND run.assignment_id = p_assignment)
         OR (p_membership IS NOT NULL AND run.direct_instructor_membership_id = p_membership))
       AND latest.phase IN ('prepared', 'gradingDispatched');
    UPDATE public.rehearsal_run SET lifecycle = 'discardedSourceContextRemoved',
        terminal_at = public.ple_rehearsal_now(), updated_at = public.ple_rehearsal_now()
     WHERE tenant_id = p_tenant AND lifecycle = 'active'
       AND ((p_course IS NOT NULL AND course_id = p_course)
         OR (p_assignment IS NOT NULL AND assignment_id = p_assignment)
         OR (p_membership IS NOT NULL AND direct_instructor_membership_id = p_membership));
    GET DIAGNOSTICS fenced = ROW_COUNT;
    RETURN fenced;
END
$$;
CREATE FUNCTION public.ple_fence_rehearsals_for_source_removal(
    p_tenant uuid, p_course uuid, p_assignment uuid, p_membership uuid,
    p_job uuid, p_lease_token uuid, p_reason text
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE fenced bigint;
BEGIN
    IF p_tenant IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant()
       OR p_reason <> 'sourceContextRemoved'
       OR ((p_course IS NOT NULL)::integer + (p_assignment IS NOT NULL)::integer
           + (p_membership IS NOT NULL)::integer) <> 1 THEN
        RAISE EXCEPTION 'invalid rehearsal source-removal capability' USING ERRCODE = '42501';
    END IF;
    PERFORM 1 FROM public.worker_job job
      JOIN public.course_retention_dispatch dispatch ON dispatch.tenant_id = job.tenant_id
       AND dispatch.job_id = job.job_id
      JOIN public.course_retention_stage stage ON stage.tenant_id = dispatch.tenant_id
       AND stage.course_id = dispatch.course_id AND stage.generation = dispatch.generation
       AND stage.stage = dispatch.stage
     WHERE job.job_id = p_job AND job.tenant_id = p_tenant AND job.state = 'leased'
       AND job.lease_token = p_lease_token AND job.lease_expires_at > transaction_timestamp()
       AND dispatch.stage = 'deleteStudentRecords' AND stage.state = 'started'
       AND stage.job_id = p_job AND stage.lease_token = p_lease_token
       AND (
            (p_course IS NOT NULL AND dispatch.course_id = p_course)
            OR (p_assignment IS NOT NULL AND EXISTS (
                SELECT 1 FROM public.assignment assignment_record
                 WHERE assignment_record.tenant_id = p_tenant
                   AND assignment_record.course_id = dispatch.course_id
                   AND assignment_record.assignment_id = p_assignment
            ))
            OR (p_membership IS NOT NULL AND EXISTS (
                SELECT 1 FROM public.course_member membership
                 WHERE membership.tenant_id = p_tenant
                   AND membership.course_id = dispatch.course_id
                   AND membership.course_membership_id = p_membership
            ))
       )
     FOR UPDATE OF job, stage;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'retention lease is not authorized for rehearsal fence' USING ERRCODE = '42501';
    END IF;
    SELECT public.ple_rehearsal_fence_source_context(p_tenant, p_course, p_assignment, p_membership)
      INTO fenced;
    RETURN fenced;
END
$$;
CREATE FUNCTION public.ple_fence_rehearsals_for_direct_instructor_removal(
    p_tenant uuid, p_actor uuid, p_course uuid, p_membership uuid
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE fenced bigint;
BEGIN
    IF p_tenant IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant()
       OR p_actor IS NULL OR p_course IS NULL OR p_membership IS NULL THEN RETURN NULL; END IF;
    PERFORM 1 FROM public.course_member actor_membership
     WHERE actor_membership.tenant_id = p_tenant AND actor_membership.course_id = p_course
       AND actor_membership.user_id = p_actor AND actor_membership.role = 'instructor'
       AND actor_membership.status = 'active';
    IF NOT FOUND THEN RETURN NULL; END IF;
    PERFORM 1 FROM public.course_member target_membership
     WHERE target_membership.tenant_id = p_tenant AND target_membership.course_id = p_course
       AND target_membership.course_membership_id = p_membership
       AND target_membership.role = 'instructor' AND target_membership.status = 'active' FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT public.ple_rehearsal_fence_source_context(p_tenant, NULL, NULL, p_membership) INTO fenced;
    RETURN fenced;
END
$$;
CREATE OR REPLACE FUNCTION public.ple_commit_delete_retention_work(
    p_tenant uuid, p_job uuid, p_token uuid, p_course uuid, p_stage text, p_generation bigint
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE committed boolean; disposition text; incoming_tenant uuid;
BEGIN
    incoming_tenant := public.ple_current_tenant();
    IF incoming_tenant IS NULL OR p_tenant IS NULL OR incoming_tenant <> p_tenant THEN
        RAISE EXCEPTION 'retention tenant authority mismatch' USING ERRCODE = '42501';
    END IF;
    SELECT assignment_disposition INTO disposition FROM public.course_retention
     WHERE tenant_id = p_tenant AND course_id = p_course AND generation = p_generation FOR UPDATE;
    IF disposition = 'delete' THEN
        BEGIN
            PERFORM public.ple_fence_rehearsals_for_source_removal(
                p_tenant, p_course, NULL, NULL, p_job, p_token, 'sourceContextRemoved'
            );
            committed := public.ple_commit_delete_retention_work_before_passwordless_identity(
                p_tenant, p_job, p_token, p_course, p_stage, p_generation
            );
            IF NOT committed THEN RAISE EXCEPTION 'retention delete did not commit' USING ERRCODE = 'P1T04'; END IF;
        EXCEPTION WHEN SQLSTATE 'P1T04' THEN RETURN false;
        END;
    ELSE
        committed := public.ple_commit_delete_retention_work_before_passwordless_identity(
            p_tenant, p_job, p_token, p_course, p_stage, p_generation
        );
        IF NOT committed THEN RETURN false; END IF;
    END IF;
    DELETE FROM public.course_total_export_audit WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_grade_category_assignment WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_grade_letter_band WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_grade_category WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_grade_scheme WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_grade_export_audit WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_roster_import WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.course_invitation WHERE tenant_id = p_tenant AND course_id = p_course;
    DELETE FROM public.tenant_learner_identity learner WHERE learner.tenant_id = p_tenant
      AND NOT EXISTS (SELECT 1 FROM public.course_member membership WHERE membership.tenant_id = learner.tenant_id AND membership.user_id = learner.user_id AND membership.role = 'student')
      AND NOT EXISTS (SELECT 1 FROM public.enrollment enrollment WHERE enrollment.tenant_id = learner.tenant_id AND enrollment.user_id = learner.user_id);
    RETURN NOT EXISTS (
        SELECT 1 FROM public.course_invitation WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_roster_profile WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_grade_export_audit WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_total_export_audit WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_grade_category_assignment WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_grade_letter_band WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_grade_category WHERE tenant_id = p_tenant AND course_id = p_course
        UNION ALL SELECT 1 FROM public.course_grade_scheme WHERE tenant_id = p_tenant AND course_id = p_course
    );
END
$$;
CREATE FUNCTION public.ple_assert_tenant_rehearsal_erasure_allowed(p_tenant uuid) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
BEGIN
    IF p_tenant IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant()
       OR EXISTS (SELECT 1 FROM public.rehearsal_run WHERE tenant_id = p_tenant) THEN
        RAISE EXCEPTION 'tenant deletion is blocked by retained rehearsal evidence' USING ERRCODE = '55000';
    END IF;
    RETURN true;
END
$$;
