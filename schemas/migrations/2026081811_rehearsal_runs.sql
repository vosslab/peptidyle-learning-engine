CREATE FUNCTION public.ple_rehearsal_append_claim_event(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_revision bigint, p_run uuid,
    p_claim uuid, p_operation uuid, p_phase text, p_abandonment_reason text DEFAULT NULL
) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE membership uuid; latest record; next_generation bigint;
BEGIN
    membership := public.ple_rehearsal_authorize_current(p_tenant, p_actor, p_course, p_assignment, p_revision);
    IF membership IS NULL OR p_run IS NULL OR p_claim IS NULL OR p_operation IS NULL THEN RETURN false; END IF;
    PERFORM 1 FROM public.rehearsal_submission_claim_root root
      JOIN public.rehearsal_run run ON run.tenant_id = root.tenant_id AND run.rehearsal_run_id = root.rehearsal_run_id
     WHERE root.tenant_id = p_tenant AND root.rehearsal_run_id = p_run AND root.claim_id = p_claim
       AND run.course_id = p_course AND run.assignment_id = p_assignment AND run.actor_id = p_actor
       AND run.direct_instructor_membership_id = membership AND run.assignment_revision = p_revision
       AND run.lifecycle = 'active' FOR UPDATE OF run;
    IF NOT FOUND THEN RETURN false; END IF;
    SELECT sequence, operation_id, generation, phase INTO latest
      FROM public.rehearsal_submission_claim_event
     WHERE tenant_id = p_tenant AND rehearsal_run_id = p_run AND claim_id = p_claim
     ORDER BY sequence DESC LIMIT 1;
    IF NOT FOUND THEN RETURN false; END IF;
    IF p_phase = 'gradingDispatched' AND latest.phase = 'prepared'
       AND p_operation = latest.operation_id AND p_abandonment_reason IS NULL THEN
        next_generation := latest.generation;
    ELSIF p_phase = 'abandonedBeforeDispatch' AND latest.phase = 'prepared'
       AND p_operation = latest.operation_id
       AND p_abandonment_reason IN (
           'localPreparationFailed', 'nativeBackendAdmissionRejected',
           'trustedRendererAdmissionRejected'
       ) THEN
        next_generation := latest.generation;
    ELSIF p_phase = 'prepared' AND latest.phase = 'abandonedBeforeDispatch'
       AND p_abandonment_reason IS NULL AND latest.generation < 4294967295
       AND NOT EXISTS (
           SELECT 1 FROM public.rehearsal_submission_claim_event event
            WHERE event.tenant_id = p_tenant AND event.rehearsal_run_id = p_run
              AND event.claim_id = p_claim AND event.operation_id = p_operation
       ) THEN
        next_generation := latest.generation + 1;
    ELSE
        RETURN false;
    END IF;
    INSERT INTO public.rehearsal_submission_claim_event (
        tenant_id, rehearsal_run_id, claim_id, sequence, operation_id, generation, phase, abandonment_reason
    ) VALUES (
        p_tenant, p_run, p_claim, latest.sequence + 1, p_operation, next_generation, p_phase,
        p_abandonment_reason
    );
    RETURN true;
END
$$;
CREATE FUNCTION public.ple_rehearsal_complete_claim(
    p_tenant uuid, p_actor uuid, p_course uuid, p_assignment uuid, p_revision bigint, p_run uuid,
    p_claim uuid, p_operation uuid, p_old_digest bytea, p_old_length bigint, p_entry_digest bytea,
    p_evidence_payload jsonb, p_evidence_payload_digest bytea, p_recorded_at_millis bigint,
    p_receipt_projection jsonb, p_receipt_digest bytea
) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public', pg_temp
    AS $$
DECLARE latest record; membership uuid;
BEGIN
    membership := public.ple_rehearsal_authorize_current(
        p_tenant, p_actor, p_course, p_assignment, p_revision
    );
    IF membership IS NULL OR p_claim IS NULL OR p_operation IS NULL
       OR p_recorded_at_millis <> public.ple_rehearsal_now_millis()
       OR jsonb_typeof(p_receipt_projection) <> 'object'
       OR public.ple_rehearsal_jsonb_bytes(p_receipt_projection) > 394240
       OR octet_length(p_receipt_digest) <> 32 THEN RETURN false; END IF;
    PERFORM 1 FROM public.rehearsal_submission_claim_root root
      JOIN public.rehearsal_run run ON run.tenant_id = root.tenant_id AND run.rehearsal_run_id = root.rehearsal_run_id
