BEGIN
    IF p_limit NOT BETWEEN 1 AND 101 OR (p_after_reference IS NOT NULL AND p_after_reference < 1) THEN RAISE EXCEPTION 'Blueprint page carries a bounded route cursor' USING ERRCODE = '22023'; END IF;
