CREATE FUNCTION public.ple_get_curriculum_alpha_v1(p_tenant uuid, p_session character(64), p_reference integer)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
DECLARE v_actor uuid; v_alpha public.alpha_course%ROWTYPE;
BEGIN
    SELECT actor.user_id INTO v_actor FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant) AS actor; IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT * INTO v_alpha FROM public.alpha_course WHERE alpha_course_reference = p_reference; IF NOT FOUND THEN RETURN NULL; END IF;
    RETURN jsonb_build_object(
        'alphaCourseId', v_alpha.alpha_course_id, 'reference', v_alpha.alpha_course_reference,
        'title', v_alpha.title, 'creatorByline', v_alpha.creator_public_byline,
        'revision', v_alpha.revision,
        'access', CASE WHEN v_alpha.creator_tenant_id = p_tenant AND v_alpha.creator_user_id = v_actor
            THEN 'creator' ELSE 'approvedInstructor' END,
        'modules', coalesce((
            SELECT jsonb_agg(jsonb_build_object('position', module_row.position, 'label', module_row.label,
                'definitions', coalesce((
                    SELECT jsonb_agg(jsonb_build_object(
                        'position', definition_row.position,
                        'definition', definition_row.definition_json || jsonb_build_object('entries', coalesce((
                            SELECT jsonb_agg(entry_document.document ORDER BY entry_document.position)
                              FROM (
                                SELECT entry_row.position, jsonb_build_object(
                                    'kind', 'fixed', 'problemId', fixed_row.problem_id,
                                    'versionId', fixed_row.version_id, 'catalog',
                                    public.ple_reusable_pinned_catalog_v1(fixed_row.problem_id, fixed_row.version_id),
                                    'pointsPossible', fixed_row.points_possible::text,
                                    'scoringMode', fixed_row.scoring_mode
                                ) AS document
                                  FROM public.alpha_course_entry AS entry_row
                                  JOIN public.alpha_course_fixed AS fixed_row
                                    ON (fixed_row.alpha_course_id, fixed_row.module_position,
                                        fixed_row.definition_position, fixed_row.position) =
                                       (entry_row.alpha_course_id, entry_row.module_position,
                                        entry_row.definition_position, entry_row.position)
                                 WHERE (entry_row.alpha_course_id, entry_row.module_position,
                                        entry_row.definition_position) =
                                       (definition_row.alpha_course_id, definition_row.module_position,
                                        definition_row.position)
                                   AND entry_row.kind = 'fixed'
                                UNION ALL
                                SELECT entry_row.position, jsonb_build_object(
                                    'kind', 'pool', 'drawCount', pool_row.draw_count,
                                    'pointsPerItem', pool_row.points_per_item::text,
                                    'ordering', pool_row.ordering_policy, 'algorithm', 'v1',
                                    'candidates', coalesce((
                                        SELECT jsonb_agg(jsonb_build_object(
                                            'problemId', candidate.problem_id,
                                            'versionId', candidate.version_id, 'catalog',
                                            public.ple_reusable_pinned_catalog_v1(candidate.problem_id, candidate.version_id)
                                        ) ORDER BY candidate.position)
                                          FROM public.alpha_course_pool_candidate AS candidate
                                         WHERE (candidate.alpha_course_id, candidate.module_position,
                                                candidate.definition_position, candidate.pool_position) =
                                               (pool_row.alpha_course_id, pool_row.module_position,
                                                pool_row.definition_position, pool_row.position)
                                    ), '[]'::jsonb)
                                ) AS document
                                  FROM public.alpha_course_entry AS entry_row
                                  JOIN public.alpha_course_pool AS pool_row
                                    ON (pool_row.alpha_course_id, pool_row.module_position,
                                        pool_row.definition_position, pool_row.position) =
                                       (entry_row.alpha_course_id, entry_row.module_position,
                                        entry_row.definition_position, entry_row.position)
                                 WHERE (entry_row.alpha_course_id, entry_row.module_position,
                                        entry_row.definition_position) =
                                       (definition_row.alpha_course_id, definition_row.module_position,
                                        definition_row.position)
                                   AND entry_row.kind = 'pool'
                            ) AS entry_document
                        ), '[]'::jsonb))
                    ) ORDER BY definition_row.position)
                      FROM public.alpha_course_definition AS definition_row
                     WHERE definition_row.alpha_course_id = module_row.alpha_course_id
                       AND definition_row.module_position = module_row.position
                ), '[]'::jsonb)) ORDER BY module_row.position)
              FROM public.alpha_course_module AS module_row
             WHERE module_row.alpha_course_id = v_alpha.alpha_course_id
        ), '[]'::jsonb)
    );
END $$;

