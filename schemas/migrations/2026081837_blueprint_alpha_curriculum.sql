CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE public.course_blueprint (
    tenant_id uuid NOT NULL,
    blueprint_id uuid NOT NULL DEFAULT gen_random_uuid(),
    blueprint_reference integer GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME public.course_blueprint_reference_seq),
    owner_user_id uuid NOT NULL,
    definition_json jsonb NOT NULL,
    semantic_sha256 bytea NOT NULL,
    revision bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    PRIMARY KEY (tenant_id, blueprint_id), UNIQUE (blueprint_reference),
    FOREIGN KEY (owner_user_id) REFERENCES public.ple_account(user_id) ON DELETE RESTRICT,
    CHECK (blueprint_reference > 0), CHECK (jsonb_typeof(definition_json) = 'object'),
    CHECK (octet_length(semantic_sha256) = 32), CHECK (revision > 0)
);
CREATE TABLE public.course_blueprint_entry (
    tenant_id uuid NOT NULL, blueprint_id uuid NOT NULL, position integer NOT NULL, kind text NOT NULL,
    PRIMARY KEY (tenant_id, blueprint_id, position),
    FOREIGN KEY (tenant_id, blueprint_id) REFERENCES public.course_blueprint ON DELETE CASCADE,
    CHECK (position >= 0), CHECK (kind IN ('fixed', 'pool'))
);
CREATE TABLE public.course_blueprint_fixed (
    tenant_id uuid NOT NULL, blueprint_id uuid NOT NULL, position integer NOT NULL,
    problem_id uuid NOT NULL, version_id uuid NOT NULL, points_possible numeric(16, 4) NOT NULL,
    scoring_mode text NOT NULL,
    PRIMARY KEY (tenant_id, blueprint_id, position),
    FOREIGN KEY (tenant_id, blueprint_id, position) REFERENCES public.course_blueprint_entry ON DELETE CASCADE,
    FOREIGN KEY (problem_id, version_id) REFERENCES public.problem_version ON DELETE RESTRICT,
    CHECK (points_possible >= 0), CHECK (scoring_mode IN ('normal', 'fullCredit', 'extraCredit', 'excluded'))
);
CREATE TABLE public.course_blueprint_pool (
    tenant_id uuid NOT NULL, blueprint_id uuid NOT NULL, position integer NOT NULL,
    draw_count integer NOT NULL, points_per_item numeric(16, 4) NOT NULL,
    ordering_policy text NOT NULL, algorithm_version smallint NOT NULL,
    PRIMARY KEY (tenant_id, blueprint_id, position),
    FOREIGN KEY (tenant_id, blueprint_id, position) REFERENCES public.course_blueprint_entry ON DELETE CASCADE,
    CHECK (draw_count > 0), CHECK (points_per_item >= 0),
    CHECK (ordering_policy IN ('candidateOrder', 'randomized')), CHECK (algorithm_version = 1)
);
CREATE TABLE public.course_blueprint_pool_candidate (
    tenant_id uuid NOT NULL, blueprint_id uuid NOT NULL, pool_position integer NOT NULL,
    position integer NOT NULL, problem_id uuid NOT NULL, version_id uuid NOT NULL,
    PRIMARY KEY (tenant_id, blueprint_id, pool_position, position),
    UNIQUE (tenant_id, blueprint_id, pool_position, problem_id, version_id),
    FOREIGN KEY (tenant_id, blueprint_id, pool_position) REFERENCES public.course_blueprint_pool ON DELETE CASCADE,
    FOREIGN KEY (problem_id, version_id) REFERENCES public.problem_version ON DELETE RESTRICT,
    CHECK (position >= 0)
);

