CREATE FUNCTION public.ple_reusable_curriculum_instructor_actor(p_session character(64), p_tenant uuid)
RETURNS TABLE (user_id uuid) LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
DECLARE v_actor uuid;
BEGIN
    IF p_tenant IS NULL OR p_session IS NULL OR p_tenant IS DISTINCT FROM public.ple_current_tenant() THEN RAISE EXCEPTION 'reusable curriculum request has a valid tenant and session' USING ERRCODE = '22023'; END IF;
    SELECT actor.user_id INTO v_actor FROM public.ple_catalog_discovery_actor(p_session, p_tenant) AS actor;
    IF NOT FOUND THEN RETURN; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.auth_session AS session WHERE session.user_id = v_actor AND session.tenant_id = p_tenant AND session.session_hash = p_session AND session.revoked_at IS NULL AND session.expires_at > transaction_timestamp() AND session.roles @> '["instructor"]'::jsonb) OR NOT public.ple_instructor_approval_eligible(v_actor) THEN RAISE EXCEPTION 'reusable curriculum requires approved Instructor authority' USING ERRCODE = '42501'; END IF;
    user_id := v_actor; RETURN NEXT;
END $$;
CREATE FUNCTION public.ple_reusable_curriculum_preflight_v1(p_tenant uuid, p_session character(64), p_capability text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
BEGIN
    IF p_capability NOT IN ('blueprintPersonal', 'alphaRead', 'alphaCreatorWrite') THEN RAISE EXCEPTION 'reusable curriculum capability is recognized' USING ERRCODE = '22023'; END IF;
    RETURN EXISTS (SELECT 1 FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant));
END $$;
CREATE FUNCTION public.ple_reusable_resolve_definition_v1(p_tenant uuid, p_definition jsonb, p_public_only boolean)
RETURNS void LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_requested integer; v_resolved integer;
BEGIN
    SELECT count(*) INTO v_requested FROM jsonb_array_elements(p_definition->'entries') AS entry(value) CROSS JOIN LATERAL jsonb_array_elements_text(CASE WHEN entry.value->>'kind' = 'fixed' THEN jsonb_build_array(entry.value->>'questionId') ELSE entry.value->'candidates' END) AS question(question_id);
    SELECT count(*) INTO v_resolved FROM jsonb_array_elements(p_definition->'entries') AS entry(value) CROSS JOIN LATERAL jsonb_array_elements_text(CASE WHEN entry.value->>'kind' = 'fixed' THEN jsonb_build_array(entry.value->>'questionId') ELSE entry.value->'candidates' END) AS question(question_id) JOIN public.catalog_search_document AS document ON document.question_id = replace(question.question_id, '-', '') AND document.lifecycle = 'published' AND (NOT p_public_only OR document.publication_scope = 'public');
    IF v_requested <> v_resolved THEN RAISE EXCEPTION 'reusable definition resolves every visible published Question ID' USING ERRCODE = '22023'; END IF;
END $$;
CREATE FUNCTION public.ple_reusable_pinned_catalog_v1(p_problem_id uuid, p_version_id uuid)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
    SELECT jsonb_build_object(
        'questionId', document.question_id, 'selectionAvailable',
        document.lifecycle = 'published' AND (
            document.publication_scope = 'public' OR EXISTS (
                SELECT 1 FROM public.catalog_tenant_grant AS grant_row
                 WHERE grant_row.tenant_id = public.ple_current_tenant()
                   AND grant_row.problem_id = document.problem_id
                   AND grant_row.version_id = document.version_id
            )
        ),
        'backend', document.backend, 'responseFamily', document.response_family,
        'capabilities', document.capabilities, 'metadata', document.metadata,
        'byline', jsonb_build_object('names', document.public_byline),
        'scope', document.publication_scope,
        'lifecycle', CASE WHEN document.lifecycle = 'published' THEN
            jsonb_build_object('state', 'published')
        ELSE jsonb_build_object('state', document.lifecycle, 'reason', document.lifecycle_reason)
        END,
        'publishedAt', floor(extract(epoch FROM document.published_at) * 1000)::bigint,
        'evidence', CASE WHEN evidence.evidence_sequence IS NULL THEN
            jsonb_build_object('state', 'insufficientEvidence')
        ELSE jsonb_build_object(
            'state', 'available', 'formulaVersion', evidence.formula_version,
            'observedCourseCount', evidence.course_count,
            'independentLearnerObservationCount', evidence.first_attempt_count,
            'difficultyIndex', evidence.difficulty_index, 'attemptsMean', evidence.attempts_mean,
            'timeMedianSecondsEstimate', evidence.time_median_seconds_estimate,
            'discriminationIndex', evidence.discrimination_index,
            'evidenceAt', floor(extract(epoch FROM evidence.evidence_at) * 1000)::bigint
        ) END
    ) FROM public.catalog_search_document AS document
    LEFT JOIN LATERAL public.ple_catalog_discovery_evidence_at(
        document.problem_id, document.version_id,
        (SELECT coalesce(max(evidence_sequence), 0) FROM public.catalog_discovery_evidence_revision)
    ) AS evidence ON true
     WHERE document.problem_id = p_problem_id AND document.version_id = p_version_id
$$;

-- Replacement first validates and resolves every Question ID.  The parent lock,
-- digest comparison, and child delete/insert form one transaction boundary.
CREATE FUNCTION public.ple_replace_curriculum_blueprint_v1(p_tenant uuid, p_session character(64), p_reference integer, p_expected_revision bigint, p_definition jsonb)
RETURNS TABLE (blueprint_reference integer, revision bigint) LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_actor uuid; v_blueprint public.course_blueprint%ROWTYPE; v_digest bytea; v_changed boolean;
BEGIN
    IF (p_expected_revision IS NOT NULL AND p_expected_revision < 1) OR NOT public.ple_reusable_definition_v1_is_valid(p_definition) THEN RAISE EXCEPTION 'Blueprint replacement carries one complete valid definition' USING ERRCODE = '22023'; END IF;
    SELECT actor.user_id INTO v_actor FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant) AS actor; IF NOT FOUND THEN RETURN; END IF;
    PERFORM public.ple_reusable_resolve_definition_v1(p_tenant, p_definition, false); v_digest := digest(convert_to(p_definition::text, 'UTF8'), 'sha256');
    IF p_reference IS NULL THEN
        IF p_expected_revision IS NOT NULL THEN RAISE EXCEPTION 'new Blueprint uses no prior revision' USING ERRCODE = '55000'; END IF;
        INSERT INTO public.course_blueprint (tenant_id, owner_user_id, definition_json, semantic_sha256) VALUES (p_tenant, v_actor, p_definition - 'entries', v_digest) RETURNING * INTO v_blueprint; v_changed := true;
    ELSE
        SELECT blueprint.* INTO v_blueprint FROM public.course_blueprint AS blueprint WHERE blueprint.tenant_id = p_tenant AND blueprint.blueprint_reference = p_reference AND blueprint.owner_user_id = v_actor FOR UPDATE; IF NOT FOUND THEN RETURN; END IF;
        IF p_expected_revision IS NULL OR v_blueprint.revision <> p_expected_revision THEN RAISE EXCEPTION 'Blueprint revision is current before replacement' USING ERRCODE = '55000'; END IF;
        v_changed := v_blueprint.semantic_sha256 IS DISTINCT FROM v_digest;
        IF v_changed THEN DELETE FROM public.course_blueprint_entry WHERE tenant_id = p_tenant AND blueprint_id = v_blueprint.blueprint_id; UPDATE public.course_blueprint AS blueprint SET definition_json = p_definition - 'entries', semantic_sha256 = v_digest, revision = blueprint.revision + 1, updated_at = transaction_timestamp() WHERE blueprint.tenant_id = p_tenant AND blueprint.blueprint_id = v_blueprint.blueprint_id RETURNING blueprint.* INTO v_blueprint; END IF;
    END IF;
    IF v_changed THEN
        INSERT INTO public.course_blueprint_entry SELECT p_tenant, v_blueprint.blueprint_id, ordinal - 1, entry.value->>'kind' FROM jsonb_array_elements(p_definition->'entries') WITH ORDINALITY AS entry(value, ordinal);
        INSERT INTO public.course_blueprint_fixed SELECT p_tenant, v_blueprint.blueprint_id, ordinal - 1, document.problem_id, document.version_id, (entry.value->>'pointsPossible')::numeric, entry.value->>'scoringMode' FROM jsonb_array_elements(p_definition->'entries') WITH ORDINALITY AS entry(value, ordinal) JOIN public.catalog_search_document AS document ON document.question_id = replace(entry.value->>'questionId', '-', '') WHERE entry.value->>'kind' = 'fixed';
        INSERT INTO public.course_blueprint_pool SELECT p_tenant, v_blueprint.blueprint_id, ordinal - 1, (entry.value->>'drawCount')::integer, (entry.value->>'pointsPerItem')::numeric, entry.value->>'ordering', 1 FROM jsonb_array_elements(p_definition->'entries') WITH ORDINALITY AS entry(value, ordinal) WHERE entry.value->>'kind' = 'pool';
        INSERT INTO public.course_blueprint_pool_candidate SELECT p_tenant, v_blueprint.blueprint_id, entry.ordinal - 1, candidate.ordinal - 1, document.problem_id, document.version_id FROM jsonb_array_elements(p_definition->'entries') WITH ORDINALITY AS entry(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements_text(entry.value->'candidates') WITH ORDINALITY AS candidate(question_id, ordinal) JOIN public.catalog_search_document AS document ON document.question_id = replace(candidate.question_id, '-', '') WHERE entry.value->>'kind' = 'pool';
    END IF;
    blueprint_reference := v_blueprint.blueprint_reference; revision := v_blueprint.revision; RETURN NEXT;
END $$;
CREATE FUNCTION public.ple_delete_curriculum_blueprint_v1(p_tenant uuid, p_session character(64), p_reference integer, p_expected_revision bigint)
RETURNS boolean LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_actor uuid; v_blueprint public.course_blueprint%ROWTYPE;
BEGIN
    SELECT actor.user_id INTO v_actor FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant) AS actor; IF NOT FOUND THEN RETURN false; END IF;
    SELECT * INTO v_blueprint FROM public.course_blueprint WHERE tenant_id = p_tenant AND blueprint_reference = p_reference AND owner_user_id = v_actor FOR UPDATE; IF NOT FOUND THEN RETURN false; END IF;
    IF p_expected_revision IS NULL OR p_expected_revision < 1 OR v_blueprint.revision <> p_expected_revision THEN RAISE EXCEPTION 'Blueprint deletion uses the current revision' USING ERRCODE = '55000'; END IF;
    DELETE FROM public.course_blueprint WHERE tenant_id = p_tenant AND blueprint_id = v_blueprint.blueprint_id; RETURN true;
END $$;
