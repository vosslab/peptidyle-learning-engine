CREATE FUNCTION public.ple_get_curriculum_blueprint_v1(p_tenant uuid, p_session character(64), p_reference integer)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
DECLARE v_actor uuid; v_blueprint public.course_blueprint%ROWTYPE;
BEGIN
    SELECT actor.user_id INTO v_actor FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant) AS actor; IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT * INTO v_blueprint FROM public.course_blueprint WHERE tenant_id = p_tenant AND owner_user_id = v_actor AND blueprint_reference = p_reference; IF NOT FOUND THEN RETURN NULL; END IF;
    RETURN jsonb_build_object(
        'blueprintId', v_blueprint.blueprint_id, 'reference', v_blueprint.blueprint_reference,
        'revision', v_blueprint.revision, 'access', 'owner', 'definition',
        v_blueprint.definition_json || jsonb_build_object('entries', coalesce((
            SELECT jsonb_agg(entry_document.document ORDER BY entry_document.position)
              FROM (
                SELECT entry_row.position, jsonb_build_object(
                    'kind', 'fixed', 'problemId', fixed_row.problem_id,
                    'versionId', fixed_row.version_id, 'catalog',
                    public.ple_reusable_pinned_catalog_v1(fixed_row.problem_id, fixed_row.version_id),
                    'pointsPossible', fixed_row.points_possible::text,
                    'scoringMode', fixed_row.scoring_mode
                ) AS document
                  FROM public.course_blueprint_entry AS entry_row
                  JOIN public.course_blueprint_fixed AS fixed_row
                    ON fixed_row.tenant_id = entry_row.tenant_id
                   AND fixed_row.blueprint_id = entry_row.blueprint_id
                   AND fixed_row.position = entry_row.position
                 WHERE entry_row.tenant_id = p_tenant AND entry_row.blueprint_id = v_blueprint.blueprint_id
                   AND entry_row.kind = 'fixed'
                UNION ALL
                SELECT entry_row.position, jsonb_build_object(
                    'kind', 'pool', 'drawCount', pool_row.draw_count,
                    'pointsPerItem', pool_row.points_per_item::text,
                    'ordering', pool_row.ordering_policy,
                    'algorithm', 'v1', 'candidates', coalesce((
                        SELECT jsonb_agg(jsonb_build_object(
                            'problemId', candidate.problem_id, 'versionId', candidate.version_id,
                            'catalog', public.ple_reusable_pinned_catalog_v1(candidate.problem_id, candidate.version_id)
                        ) ORDER BY candidate.position)
                          FROM public.course_blueprint_pool_candidate AS candidate
                         WHERE candidate.tenant_id = pool_row.tenant_id
                           AND candidate.blueprint_id = pool_row.blueprint_id
                           AND candidate.pool_position = pool_row.position
                    ), '[]'::jsonb)
                ) AS document
                  FROM public.course_blueprint_entry AS entry_row
                  JOIN public.course_blueprint_pool AS pool_row
                    ON pool_row.tenant_id = entry_row.tenant_id
                   AND pool_row.blueprint_id = entry_row.blueprint_id
                   AND pool_row.position = entry_row.position
                 WHERE entry_row.tenant_id = p_tenant AND entry_row.blueprint_id = v_blueprint.blueprint_id
                   AND entry_row.kind = 'pool'
            ) AS entry_document
        ), '[]'::jsonb))
    );
END $$;

-- Alpha creates/replaces its complete labelled tree under the creator's lock.
CREATE FUNCTION public.ple_replace_curriculum_alpha_v1(p_tenant uuid, p_session character(64), p_reference integer, p_expected_revision bigint, p_alpha jsonb)
RETURNS TABLE (alpha_course_reference integer, revision bigint) LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_actor uuid; v_alpha public.alpha_course%ROWTYPE; v_digest bytea; v_byline text[]; v_changed boolean;
BEGIN
    IF (p_expected_revision IS NOT NULL AND p_expected_revision < 1) OR NOT public.ple_reusable_alpha_v1_is_valid(p_alpha) THEN RAISE EXCEPTION 'Alpha replacement carries a complete valid curriculum' USING ERRCODE = '22023'; END IF;
    SELECT actor.user_id INTO v_actor FROM public.ple_reusable_curriculum_instructor_actor(p_session, p_tenant) AS actor; IF NOT FOUND THEN RETURN; END IF;
    SELECT ARRAY[account.display_name] INTO v_byline FROM public.ple_account AS account WHERE account.user_id = v_actor; IF NOT FOUND OR NOT public.ple_valid_public_byline(v_byline) THEN RAISE EXCEPTION 'Alpha creator has a reviewed public byline' USING ERRCODE = '42501'; END IF;
    PERFORM public.ple_reusable_resolve_definition_v1(p_tenant, definition.value, true) FROM jsonb_array_elements(p_alpha->'modules') AS module(value) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') AS definition(value);
    v_digest := digest(convert_to(p_alpha::text, 'UTF8'), 'sha256');
    IF p_reference IS NULL THEN
        IF p_expected_revision IS NOT NULL THEN RAISE EXCEPTION 'new Alpha uses no prior revision' USING ERRCODE = '55000'; END IF;
        INSERT INTO public.alpha_course (creator_tenant_id, creator_user_id, title, creator_public_byline, semantic_sha256) VALUES (p_tenant, v_actor, p_alpha->>'title', v_byline, v_digest) RETURNING * INTO v_alpha; v_changed := true;
    ELSE
        SELECT alpha.* INTO v_alpha FROM public.alpha_course AS alpha WHERE alpha.alpha_course_reference = p_reference FOR UPDATE; IF NOT FOUND THEN RETURN; END IF;
        IF v_alpha.creator_tenant_id <> p_tenant OR v_alpha.creator_user_id <> v_actor THEN RAISE EXCEPTION 'Alpha replacement has creator authority' USING ERRCODE = '42501'; END IF;
        IF p_expected_revision IS NULL OR v_alpha.revision <> p_expected_revision THEN RAISE EXCEPTION 'Alpha revision is current before replacement' USING ERRCODE = '55000'; END IF;
        v_changed := v_alpha.semantic_sha256 IS DISTINCT FROM v_digest;
        IF v_changed THEN DELETE FROM public.alpha_course_module WHERE alpha_course_id = v_alpha.alpha_course_id; UPDATE public.alpha_course AS alpha SET title = p_alpha->>'title', semantic_sha256 = v_digest, revision = alpha.revision + 1, updated_at = transaction_timestamp() WHERE alpha.alpha_course_id = v_alpha.alpha_course_id RETURNING alpha.* INTO v_alpha; END IF;
    END IF;
    IF v_changed THEN
        INSERT INTO public.alpha_course_module SELECT v_alpha.alpha_course_id, module.ordinal - 1, module.value->>'label' FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal);
        INSERT INTO public.alpha_course_definition SELECT v_alpha.alpha_course_id, module.ordinal - 1, definition.ordinal - 1, definition.value - 'entries' FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') WITH ORDINALITY AS definition(value, ordinal);
        INSERT INTO public.alpha_course_entry SELECT v_alpha.alpha_course_id, module.ordinal - 1, definition.ordinal - 1, entry.ordinal - 1, entry.value->>'kind' FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') WITH ORDINALITY AS definition(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(definition.value->'entries') WITH ORDINALITY AS entry(value, ordinal);
        INSERT INTO public.alpha_course_fixed SELECT v_alpha.alpha_course_id, module.ordinal - 1, definition.ordinal - 1, entry.ordinal - 1, document.problem_id, document.version_id, (entry.value->>'pointsPossible')::numeric, entry.value->>'scoringMode' FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') WITH ORDINALITY AS definition(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(definition.value->'entries') WITH ORDINALITY AS entry(value, ordinal) JOIN public.catalog_search_document AS document ON document.question_id = replace(entry.value->>'questionId', '-', '') WHERE entry.value->>'kind' = 'fixed';
        INSERT INTO public.alpha_course_pool SELECT v_alpha.alpha_course_id, module.ordinal - 1, definition.ordinal - 1, entry.ordinal - 1, (entry.value->>'drawCount')::integer, (entry.value->>'pointsPerItem')::numeric, entry.value->>'ordering', 1 FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') WITH ORDINALITY AS definition(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(definition.value->'entries') WITH ORDINALITY AS entry(value, ordinal) WHERE entry.value->>'kind' = 'pool';
        INSERT INTO public.alpha_course_pool_candidate SELECT v_alpha.alpha_course_id, module.ordinal - 1, definition.ordinal - 1, entry.ordinal - 1, candidate.ordinal - 1, document.problem_id, document.version_id FROM jsonb_array_elements(p_alpha->'modules') WITH ORDINALITY AS module(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(module.value->'definitions') WITH ORDINALITY AS definition(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements(definition.value->'entries') WITH ORDINALITY AS entry(value, ordinal) CROSS JOIN LATERAL jsonb_array_elements_text(entry.value->'candidates') WITH ORDINALITY AS candidate(question_id, ordinal) JOIN public.catalog_search_document AS document ON document.question_id = replace(candidate.question_id, '-', '') WHERE entry.value->>'kind' = 'pool';
    END IF;
    alpha_course_reference := v_alpha.alpha_course_reference; revision := v_alpha.revision; RETURN NEXT;
END $$;
CREATE FUNCTION public.ple_list_curriculum_alpha_v1(p_tenant uuid, p_session character(64), p_after_reference integer, p_limit integer)
