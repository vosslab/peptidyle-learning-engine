CREATE FUNCTION public.ple_saved_problem_search_filter_v1_is_valid(p_query jsonb)
RETURNS boolean
LANGUAGE sql IMMUTABLE PARALLEL SAFE
SET search_path TO 'pg_catalog', 'public'
RETURN coalesce(
    jsonb_typeof(p_query) = 'object'
    AND p_query ?& ARRAY['text','bylines','backends','tags','responseFamilies','taxonomy',
        'capabilities','licenses','evidence','usedInMyCourses','authorship']
    AND (SELECT count(*) FROM jsonb_object_keys(p_query)) = 11
    AND CASE
        WHEN p_query->'text' = 'null'::jsonb THEN true
        WHEN jsonb_typeof(p_query->'text') = 'string' THEN
            char_length(p_query->>'text') BETWEEN 1 AND 256
            AND p_query->>'text' = lower(regexp_replace(
                btrim(p_query->>'text'), '[[:space:]]+', ' ', 'g'
            ))
        ELSE false
    END
    AND CASE WHEN jsonb_typeof(p_query->'bylines') = 'array' THEN
        jsonb_array_length(p_query->'bylines') <= 16
        AND p_query->'bylines' = (
            SELECT coalesce(jsonb_agg(item.value ORDER BY item.value#>>'{}' COLLATE "C"), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements(p_query->'bylines')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'bylines') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR char_length(item.value#>>'{}') NOT BETWEEN 1 AND 120
                OR item.value#>>'{}' <> lower(regexp_replace(
                    btrim(item.value#>>'{}'), '[[:space:]]+', ' ', 'g'
                ))
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'backends') = 'array' THEN
        jsonb_array_length(p_query->'backends') <= 5
        AND p_query->'backends' = (
            SELECT coalesce(jsonb_agg(to_jsonb(item.value) ORDER BY array_position(
                ARRAY['native','webwork','qti','h5p','imathas']::text[], item.value)), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements_text(p_query->'backends')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'backends') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR item.value#>>'{}' NOT IN ('native','webwork','qti','h5p','imathas')
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'tags') = 'array' THEN
        jsonb_array_length(p_query->'tags') <= 64
        AND p_query->'tags' = (
            SELECT coalesce(jsonb_agg(item.value ORDER BY item.value#>>'{}' COLLATE "C"), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements(p_query->'tags')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'tags') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR char_length(item.value#>>'{}') NOT BETWEEN 1 AND 256
                OR item.value#>>'{}' <> lower(regexp_replace(
                    btrim(item.value#>>'{}'), '[[:space:]]+', ' ', 'g'
                ))
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'responseFamilies') = 'array' THEN
        jsonb_array_length(p_query->'responseFamilies') <= 9
        AND p_query->'responseFamilies' = (
            SELECT coalesce(jsonb_agg(to_jsonb(item.value) ORDER BY array_position(ARRAY[
                'numeric','multipleChoice','shortText','multiBlank','matching','ordering',
                'hotspot','fileUpload','externalTool']::text[], item.value)), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements_text(p_query->'responseFamilies')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'responseFamilies') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR item.value#>>'{}' NOT IN ('numeric','multipleChoice','shortText','multiBlank',
                    'matching','ordering','hotspot','fileUpload','externalTool')
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'taxonomy') = 'array' THEN
        jsonb_array_length(p_query->'taxonomy') <= 64
        AND p_query->'taxonomy' = (
            SELECT coalesce(jsonb_agg(item.value ORDER BY item.value->>'scheme' COLLATE "C",
                item.value->>'code' COLLATE "C"), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements(p_query->'taxonomy')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'taxonomy') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'object'
                OR NOT item.value ?& ARRAY['scheme','code']
                OR (SELECT count(*) FROM jsonb_object_keys(item.value)) <> 2
                OR jsonb_typeof(item.value->'scheme') <> 'string'
                OR jsonb_typeof(item.value->'code') <> 'string'
                OR char_length(item.value->>'scheme') NOT BETWEEN 1 AND 128
                OR char_length(item.value->>'code') NOT BETWEEN 1 AND 128
                OR item.value->>'scheme' <> btrim(item.value->>'scheme')
                OR item.value->>'code' <> btrim(item.value->>'code')
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'capabilities') = 'array' THEN
        jsonb_array_length(p_query->'capabilities') <= 8
        AND p_query->'capabilities' = (
            SELECT coalesce(jsonb_agg(to_jsonb(item.value) ORDER BY array_position(ARRAY[
                'algorithmicGeneration','clientRendering','serverGrading','partialCredit','hints',
                'perQuestionTiming','printExport','offlinePreview']::text[], item.value)), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements_text(p_query->'capabilities')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'capabilities') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR item.value#>>'{}' NOT IN ('algorithmicGeneration','clientRendering',
                    'serverGrading','partialCredit','hints','perQuestionTiming','printExport',
                    'offlinePreview')
        )
        ELSE false END
    AND CASE WHEN jsonb_typeof(p_query->'licenses') = 'array' THEN
        jsonb_array_length(p_query->'licenses') <= 6
        AND p_query->'licenses' = (
            SELECT coalesce(jsonb_agg(to_jsonb(item.value) ORDER BY array_position(ARRAY[
                'allRightsReserved','ccBy','ccBySa','ccByNc','cc0','other']::text[], item.value)), '[]'::jsonb)
              FROM (SELECT DISTINCT value FROM jsonb_array_elements_text(p_query->'licenses')) AS item(value))
        AND NOT EXISTS (
            SELECT 1 FROM jsonb_array_elements(p_query->'licenses') AS item(value)
             WHERE jsonb_typeof(item.value) <> 'string'
                OR item.value#>>'{}' NOT IN (
                    'allRightsReserved','ccBy','ccBySa','ccByNc','cc0','other'
                )
        )
        ELSE false END
    AND jsonb_typeof(p_query->'evidence') = 'string'
    AND p_query->>'evidence' IN ('any','available','unavailable')
    AND jsonb_typeof(p_query->'usedInMyCourses') = 'string'
    AND p_query->>'usedInMyCourses' IN ('any','used')
    AND jsonb_typeof(p_query->'authorship') = 'string'
    AND p_query->>'authorship' IN ('any','authoredByCurrentActor'),
    false
);

