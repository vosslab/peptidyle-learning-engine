-- The application asks only for one closed capability decision. Actor and
-- role details remain inside the session-derived broker boundary.
CREATE FUNCTION public.ple_problem_curation_preflight_v1(
    p_tenant uuid, p_session character(64), p_capability text
) RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
BEGIN
    IF p_capability = 'catalogInstitutionRead' THEN
        RETURN EXISTS (
            SELECT 1 FROM public.ple_problem_curation_actor(p_session, p_tenant)
        );
    ELSIF p_capability = 'personalMutation' THEN
        RETURN EXISTS (
            SELECT 1 FROM public.ple_problem_curation_instructor_actor(p_session, p_tenant)
        );
    END IF;
    RAISE EXCEPTION 'problem curation capability is invalid' USING ERRCODE = '22023';
END
$$;

