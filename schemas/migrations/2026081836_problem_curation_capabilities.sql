CREATE FUNCTION public.ple_replace_problem_collection_v1(
    p_tenant uuid, p_session character(64), p_collection_reference integer,
    p_expected_revision bigint, p_title text, p_visibility text, p_question_ids text[]
) RETURNS TABLE (
    collection_reference integer, kind text, title text, visibility text, revision bigint
)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_actor uuid; v_collection public.problem_collection%ROWTYPE; v_new_id uuid;
DECLARE v_count integer; v_resolved_count integer; v_changed boolean;
BEGIN
    IF p_tenant IS NULL OR p_session IS NULL OR p_expected_revision IS NULL
       OR p_expected_revision < 0 OR p_title IS NULL OR p_title <> btrim(p_title)
       OR char_length(p_title) NOT BETWEEN 1 AND 200
       OR p_visibility NOT IN ('private', 'institution') OR p_question_ids IS NULL
       OR coalesce(cardinality(p_question_ids), 0) > 200
       OR p_tenant IS DISTINCT FROM public.ple_current_tenant() THEN
        RAISE EXCEPTION 'problem collection replacement arguments are invalid' USING ERRCODE = '22023';
    END IF;
    SELECT count(*) INTO v_count FROM unnest(p_question_ids) AS id(question_id);
    IF v_count <> coalesce(cardinality(p_question_ids), 0)
       OR EXISTS (SELECT 1 FROM unnest(p_question_ids) AS id(question_id)
                   WHERE id.question_id IS NULL OR id.question_id !~ '^[A-Z0-9]{7}$')
       OR (SELECT count(DISTINCT id.question_id) FROM unnest(p_question_ids) AS id(question_id)) <> v_count THEN
        RAISE EXCEPTION 'problem collection question identifiers are invalid' USING ERRCODE = '22023';
    END IF;
    SELECT actor.user_id INTO v_actor
      FROM public.ple_problem_curation_instructor_actor(p_session, p_tenant) AS actor;
    IF NOT FOUND THEN RETURN; END IF;
    IF p_collection_reference IS NULL THEN
        IF p_expected_revision <> 0 THEN
            RAISE EXCEPTION 'new problem collection revision conflicts' USING ERRCODE = '55000';
        END IF;
        PERFORM pg_advisory_xact_lock(hashtextextended(p_tenant::text || v_actor::text, 0));
        IF (SELECT count(*) FROM public.problem_collection AS c
             WHERE c.owner_tenant_id = p_tenant AND c.owner_user_id = v_actor AND c.kind = 'named') >= 100 THEN
            RAISE EXCEPTION 'named problem collection limit exceeded' USING ERRCODE = '22023';
        END IF;
        v_new_id := gen_random_uuid();
        INSERT INTO public.problem_collection
            (collection_id, owner_tenant_id, owner_user_id, kind, title, visibility)
        VALUES (v_new_id, p_tenant, v_actor, 'named', p_title, p_visibility)
        RETURNING * INTO v_collection;
    ELSE
        SELECT * INTO v_collection FROM public.problem_collection AS c
         WHERE c.owner_tenant_id = p_tenant AND c.collection_reference = p_collection_reference
           AND c.owner_user_id = v_actor FOR UPDATE;
        IF NOT FOUND THEN RETURN; END IF;
        IF v_collection.revision <> p_expected_revision THEN
            RAISE EXCEPTION 'problem collection revision conflicts' USING ERRCODE = '55000';
        END IF;
        IF v_collection.kind = 'favorites'
           AND (p_title <> 'Favorites' OR p_visibility <> 'private') THEN
            RAISE EXCEPTION 'Favorites metadata is fixed' USING ERRCODE = '22023';
        END IF;
    END IF;
    SELECT count(*) INTO v_resolved_count
      FROM unnest(p_question_ids) WITH ORDINALITY AS requested(question_id, position)
      JOIN public.catalog_search_document AS document
        ON document.question_id = requested.question_id
       AND document.lifecycle = 'published'
       AND (document.publication_scope = 'public' OR EXISTS (
            SELECT 1 FROM public.catalog_tenant_grant AS grant_row
             WHERE grant_row.tenant_id = p_tenant AND grant_row.problem_id = document.problem_id
               AND grant_row.version_id = document.version_id
       ));
    IF v_resolved_count <> v_count THEN
        RAISE EXCEPTION 'problem collection contains unavailable Question IDs' USING ERRCODE = '22023';
    END IF;
    WITH proposed AS (
        SELECT requested.position - 1 AS position, document.problem_id, document.version_id
          FROM unnest(p_question_ids) WITH ORDINALITY AS requested(question_id, position)
          JOIN public.catalog_search_document AS document
            ON document.question_id = requested.question_id AND document.lifecycle = 'published'
           AND (document.publication_scope = 'public' OR EXISTS (
                SELECT 1 FROM public.catalog_tenant_grant AS grant_row
                 WHERE grant_row.tenant_id = p_tenant AND grant_row.problem_id = document.problem_id
                   AND grant_row.version_id = document.version_id
           ))
    ), existing AS (
        SELECT position, problem_id, version_id FROM public.problem_collection_member
         WHERE owner_tenant_id = p_tenant AND collection_id = v_collection.collection_id
    ) SELECT (v_collection.title IS DISTINCT FROM p_title OR v_collection.visibility IS DISTINCT FROM p_visibility
        OR EXISTS ((SELECT * FROM proposed) EXCEPT (SELECT * FROM existing))
        OR EXISTS ((SELECT * FROM existing) EXCEPT (SELECT * FROM proposed))) INTO v_changed;
    IF v_changed THEN
        DELETE FROM public.problem_collection_member
         WHERE owner_tenant_id = p_tenant AND collection_id = v_collection.collection_id;
        INSERT INTO public.problem_collection_member
            (owner_tenant_id, collection_id, problem_id, version_id, position)
        SELECT p_tenant, v_collection.collection_id, document.problem_id, document.version_id,
               requested.position - 1
          FROM unnest(p_question_ids) WITH ORDINALITY AS requested(question_id, position)
          JOIN public.catalog_search_document AS document
            ON document.question_id = requested.question_id AND document.lifecycle = 'published'
           AND (document.publication_scope = 'public' OR EXISTS (
                SELECT 1 FROM public.catalog_tenant_grant AS grant_row
                 WHERE grant_row.tenant_id = p_tenant AND grant_row.problem_id = document.problem_id
                   AND grant_row.version_id = document.version_id
           ));
        UPDATE public.problem_collection AS collection_row
           SET title = p_title, visibility = p_visibility,
               revision = collection_row.revision + 1,
               updated_at = transaction_timestamp()
         WHERE collection_row.owner_tenant_id = p_tenant
           AND collection_row.collection_id = v_collection.collection_id
         RETURNING collection_row.* INTO v_collection;
    END IF;
    collection_reference := v_collection.collection_reference;
    kind := v_collection.kind; title := v_collection.title; visibility := v_collection.visibility;
    revision := v_collection.revision; RETURN NEXT;
END
$$;

CREATE FUNCTION public.ple_replace_saved_problem_search_v1(
    p_tenant uuid, p_session character(64), p_search_reference integer,
    p_expected_revision bigint, p_title text, p_normalized_query jsonb
) RETURNS TABLE (search_reference integer, title text, normalized_query jsonb, query_schema_version smallint, normalized_query_sha256 bytea, canonical_query_sha256 bytea, revision bigint)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public', pg_temp AS $$
DECLARE v_actor uuid; v_search public.saved_problem_search%ROWTYPE;
BEGIN
    IF p_tenant IS NULL OR p_session IS NULL OR p_expected_revision IS NULL OR p_expected_revision < 0
       OR p_title IS NULL OR p_title <> btrim(p_title) OR char_length(p_title) NOT BETWEEN 1 AND 200
       OR NOT public.ple_saved_problem_search_filter_v1_is_valid(p_normalized_query)
       OR p_tenant IS DISTINCT FROM public.ple_current_tenant() THEN
        RAISE EXCEPTION 'saved problem search replacement arguments are invalid' USING ERRCODE = '22023';
    END IF;
    SELECT actor.user_id INTO v_actor FROM public.ple_problem_curation_instructor_actor(p_session, p_tenant) AS actor;
    IF NOT FOUND THEN RETURN; END IF;
    IF p_search_reference IS NULL THEN
        IF p_expected_revision <> 0 THEN RAISE EXCEPTION 'new saved search revision conflicts' USING ERRCODE = '55000'; END IF;
        PERFORM pg_advisory_xact_lock(hashtextextended(p_tenant::text || v_actor::text, 0));
        IF (SELECT count(*) FROM public.saved_problem_search AS search_row
             WHERE search_row.owner_tenant_id = p_tenant AND search_row.owner_user_id = v_actor) >= 100 THEN
            RAISE EXCEPTION 'saved problem search limit exceeded' USING ERRCODE = '22023';
        END IF;
        INSERT INTO public.saved_problem_search(owner_tenant_id, owner_user_id, title, normalized_query, normalized_query_sha256)
        VALUES (p_tenant, v_actor, p_title, p_normalized_query,
                digest(convert_to(p_normalized_query::text, 'UTF8'), 'sha256')) RETURNING * INTO v_search;
    ELSE
        SELECT * INTO v_search FROM public.saved_problem_search AS search_row
         WHERE search_row.owner_tenant_id = p_tenant AND search_row.search_reference = p_search_reference
           AND search_row.owner_user_id = v_actor FOR UPDATE;
        IF NOT FOUND THEN RETURN; END IF;
        IF v_search.revision <> p_expected_revision THEN
            RAISE EXCEPTION 'saved problem search revision conflicts' USING ERRCODE = '55000';
        END IF;
        IF v_search.title IS DISTINCT FROM p_title OR v_search.normalized_query IS DISTINCT FROM p_normalized_query THEN
            UPDATE public.saved_problem_search AS search_row
               SET title = p_title, normalized_query = p_normalized_query,
                   normalized_query_sha256 = digest(
                       convert_to(p_normalized_query::text, 'UTF8'), 'sha256'
                   ),
                   revision = search_row.revision + 1,
                   updated_at = transaction_timestamp()
             WHERE search_row.owner_tenant_id = p_tenant
               AND search_row.search_id = v_search.search_id
             RETURNING search_row.* INTO v_search;
        END IF;
    END IF;
    search_reference := v_search.search_reference; title := v_search.title;
    normalized_query := v_search.normalized_query; query_schema_version := v_search.query_schema_version;
    normalized_query_sha256 := v_search.normalized_query_sha256;
    canonical_query_sha256 := digest(convert_to(v_search.normalized_query::text, 'UTF8'), 'sha256');
    revision := v_search.revision; RETURN NEXT;
END
$$;

