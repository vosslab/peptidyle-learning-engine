-- Favorites and named collection mutation belongs to an approved Instructor.
-- Sysadmins retain the intended institution-read capability only.
CREATE FUNCTION public.ple_problem_curation_instructor_actor(
    p_session character(64), p_tenant uuid
) RETURNS TABLE (user_id uuid)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public' AS $$
DECLARE v_actor uuid;
BEGIN
    SELECT actor.user_id INTO v_actor
      FROM public.ple_problem_curation_actor(p_session, p_tenant) AS actor;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    IF NOT EXISTS (
        SELECT 1
          FROM public.auth_session AS session
         WHERE session.user_id = v_actor
           AND session.tenant_id = p_tenant
           AND session.session_hash = p_session
           AND session.revoked_at IS NULL
           AND session.expires_at > transaction_timestamp()
           AND session.roles @> '["instructor"]'::jsonb
    ) OR NOT public.ple_instructor_approval_eligible(v_actor) THEN
        RAISE EXCEPTION 'personal problem curation requires Instructor authority'
            USING ERRCODE = '42501';
    END IF;
    user_id := v_actor;
    RETURN NEXT;
END
$$;
ALTER FUNCTION public.ple_problem_curation_instructor_actor(character, uuid)
    OWNER TO ple_problem_curation_broker;
REVOKE ALL ON FUNCTION public.ple_problem_curation_instructor_actor(character, uuid) FROM PUBLIC;
