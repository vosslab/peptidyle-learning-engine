ALTER ROLE ple_problem_curation_broker
    NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
DO $$
DECLARE
    membership_edge record;
    default_acl record;
    target_column record;
BEGIN
    -- Converge every pre-D2 membership edge in both directions before the
    -- broker receives its canonical capability.
    FOR membership_edge IN
        SELECT parent_role.rolname AS parent_name, member_role.rolname AS member_name
          FROM pg_catalog.pg_auth_members AS membership
          JOIN pg_catalog.pg_roles AS parent_role ON parent_role.oid = membership.roleid
          JOIN pg_catalog.pg_roles AS member_role ON member_role.oid = membership.member
         WHERE membership.member = 'ple_problem_curation_broker'::regrole
            OR membership.roleid = 'ple_problem_curation_broker'::regrole
    LOOP
        EXECUTE format(
            'REVOKE %I FROM %I', membership_edge.parent_name, membership_edge.member_name
        );
    END LOOP;

    -- Default grants are ambient future authority. Remove every existing
    -- table, sequence, and function default that names this broker.
    FOR default_acl IN
        SELECT DISTINCT owner_role.rolname AS owner_name, namespace.nspname AS schema_name,
               defaults.defaclobjtype
          FROM pg_catalog.pg_default_acl AS defaults
          JOIN pg_catalog.pg_roles AS owner_role ON owner_role.oid = defaults.defaclrole
          LEFT JOIN pg_catalog.pg_namespace AS namespace
            ON namespace.oid = defaults.defaclnamespace
          CROSS JOIN LATERAL aclexplode(defaults.defaclacl) AS privilege
         WHERE privilege.grantee = 'ple_problem_curation_broker'::regrole
           AND defaults.defaclobjtype IN ('r','S','f')
    LOOP
        EXECUTE format(
            'ALTER DEFAULT PRIVILEGES FOR ROLE %I%s REVOKE ALL PRIVILEGES ON %s FROM ple_problem_curation_broker',
            default_acl.owner_name,
            CASE WHEN default_acl.schema_name IS NULL THEN ''
                 ELSE format(' IN SCHEMA %I', default_acl.schema_name) END,
            CASE default_acl.defaclobjtype
                WHEN 'r' THEN 'TABLES'
                WHEN 'S' THEN 'SEQUENCES'
                WHEN 'f' THEN 'FUNCTIONS'
            END
        );
    END LOOP;

    -- Table-level revocation does not erase column ACLs, so close those
    -- direct grants explicitly before applying the exact table matrix.
    FOR target_column IN
        SELECT namespace.nspname, relation_row.relname, attribute.attname
          FROM pg_catalog.pg_attribute AS attribute
          JOIN pg_catalog.pg_class AS relation_row ON relation_row.oid = attribute.attrelid
          JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation_row.relnamespace
         WHERE namespace.nspname = 'public'
           AND relation_row.relkind IN ('r','p','v','m','f')
           AND attribute.attnum > 0 AND NOT attribute.attisdropped
           AND EXISTS (
               SELECT 1 FROM aclexplode(attribute.attacl) AS privilege
                WHERE privilege.grantee = 'ple_problem_curation_broker'::regrole
           )
    LOOP
        EXECUTE format(
            'REVOKE ALL PRIVILEGES (%I) ON TABLE %I.%I FROM ple_problem_curation_broker',
            target_column.attname, target_column.nspname, target_column.relname
        );
    END LOOP;
END
$$;
